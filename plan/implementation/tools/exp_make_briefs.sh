# block <id>: lines from `**S01-<id>**` up to (excl.) the next `**S01-` line or `## ` heading, trailing blanks dropped
block() {
  awk -v id="$1" '
    index($0, "**S01-" id "**") == 1 { on=1; print; next }
    on && (/^[*][*]S01-/ || /^## /) { exit }
    on { print }' "$S" | sed -e :a -e '/^\n*$/{$d;N;ba' -e '}'
}
# range <start-regex> <stop-regex>: from the first line matching start up to (excl.) the first later stop match
range() {
  awk -v a="$1" -v b="$2" '
    !on && $0 ~ a { on=1; print; next }
    on && $0 ~ b { exit }
    on { print }' "$S" | sed -e :a -e '/^\n*$/{$d;N;ba' -e '}'
}

LEAN_COMMON="$(range '^Common rules for all L-WPs:' '^[*][*]S01-L1[*][*]')"
TEX_COMMON="$(range '^File layout, fixed by M0' '^[*][*]S01-M0[*][*]')"
CODE_COMMON="$(range '^Tools: `cypari2`' '^[*][*]S01-C0[*][*]')"

emit() {  # emit <file> <E#> <wp-id> <title> <track-label> <common-text> <outputs> <acceptance-block> <extra-notes>
  local f="$1" e="$2" id="$3" title="$4" track="$5" common="$6" outs="$7" acc="$8" extra="$9"
  {
    printf '# Brief: S01-%s — %s\n\n' "$id" "$title"
    printf 'Experiment cell %s (EXPERIMENT_PROTOCOL). This brief is byte-identical for all strands of the work package.\n' "$e"
    printf 'Source: `plan/implementation/stage-01.md` (blob `%s`), generated by `plan/implementation/tools/exp_make_briefs.sh`.\n' "$blob"
    printf 'The stage plan, the stage tex `plan/staged/stage-01-quaternion-foundations.tex` (statements, labels) and the\n'
    printf 'conventions of `plan/implementation/stage-01.md` §0 are available in your worktree; the tex labels cited below are your statements.\n\n'
    printf '## 1. Work package (verbatim from stage-01.md)\n\n'
    block "$id"
    printf '\n\n## 2. Common rules of the track (verbatim from stage-01.md)\n\n%s\n\n' "$common"
    [ -z "$extra" ] || printf '%s\n\n' "$extra"
    printf '## 3. Output files (the only files you may create or change)\n\n%s\n\n' "$outs"
    printf '## 4. Acceptance command\n\nRun from the worktree root. It is run again, independently, by the stage master on your final commit.\n\n```bash\n%s\n```\n' "$acc"
  } > "$OUT/$f"
}

