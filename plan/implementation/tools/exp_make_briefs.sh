lean_acc() {  # lean_acc <wp> <space-separated targets rel. to lean/Langlandscape> <module> <decl...>
  local wp="$1" tg="$2" mod="$3"; shift 3
  local d; printf 'set -e\ncd lean/Langlandscape\n'
  for t in $tg; do
    printf 'flock ~/.cache/gl2tf/exp.lock tools/lfile.sh %s\n' "$t"
    printf '! grep -nE '"'"'\\bsorry\\b|\\badmit\\b|^axiom'"'"' %s\n' "$t"
  done
  printf 'cat > .exp-axioms-%s.lean <<'"'"'LEAN'"'"'\n' "$wp"
  for m in $mod; do printf 'import %s\n' "$m"; done
  for d in "$@"; do printf '#print axioms %s\n' "$d"; done
  printf 'LEAN\nflock ~/.cache/gl2tf/exp.lock tools/lfile.sh .exp-axioms-%s.lean   # git-ignored via info/exclude, never committed; output lists axioms: only the standard three allowed\n' "$wp"
}
