tex_acc() {  # tex_acc <section-file> <allowed-new-labels, space separated or ""> <label...>
  local f="$1" allow="$2"; shift 2
  local ls="$*" ok allowcmd='{ ! grep . ; }' t
  if [ -n "$allow" ]; then
    allowcmd='{ ! grep -vxF'
    for ok in $allow; do allowcmd="$allowcmd -e '\\label{$ok}'"; done
    allowcmd="$allowcmd ; }"
  fi
  read -r -d '' t <<'EOT' || true
set -e
cd mathematics
latexmk -pdf -interaction=nonstopmode main.tex
test "$(grep -c 'undefined' main.log || true)" = 0
for l in @LABELS@; do
  test "$(cat chapters/s01/*.tex | grep -cF "\\label{$l}")" = 1
done
B=$(git merge-base HEAD wip-implementation)
git grep -ohE '\\label\{[^}]*\}' "$B" -- chapters/s01 | sort -u > /tmp/base-labels.$$
cat chapters/s01/*.tex | grep -o '\\label{[^}]*}' | sort -u > /tmp/now-labels.$$
comm -23 /tmp/base-labels.$$ /tmp/now-labels.$$ | { ! grep . ; }    # no tex label removed
comm -13 /tmp/base-labels.$$ /tmp/now-labels.$$ | @ALLOWCMD@    # no tex label added (except those named in section 3)
rm -f /tmp/base-labels.$$ /tmp/now-labels.$$
awk '/\\stcited/{ if ($0 !~ /\\lit\{/) { if ((getline nx) > 0 && nx !~ /\\lit\{/) bad++ } } END{exit bad>0}' chapters/s01/@FILE@   # every \stcited has a \lit
latexmk -C main.tex
cd ..
git status --porcelain | grep -v 'mathematics/chapters/s01/@FILE@' | { ! grep . ; }   # no other file changed, no build products
EOT
  t="${t//@LABELS@/$ls}"; t="${t//@FILE@/$f}"; t="${t//@ALLOWCMD@/"$allowcmd"}"
  printf '%s\n' "$t"
}
