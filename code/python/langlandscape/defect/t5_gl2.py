"""S06-C4 (T5, GL_2 side): ``eta_f(q)``, ``eta_f(1, q)``, ``c_q(f)``, ranks and ``T_p`` at ``m_f``.

Tex: ``plan/staged/stage-06-integral-defect.tex``, computation H2 (T5); ``thm:s06-E`` (iii)
(``eta(S, lam) = c_q * eta(S', lam')`` over a DVR when ``S_m`` is Gorenstein), ``cor:s06-fixed`` (``c_q(f) =
(varpi^{t_f(q)})`` at ``k <= p - 1``).  Status of every number produced here: *computed* (exact over ``Z``, local lengths
exact, see :mod:`.hecke_alg`).

Setting.  ``N = q`` (``M = 1``), trivial character, ``S = T_kk(Gamma_0(q))`` the full Hecke algebra (generated by
``T_l``, ``l`` prime ``<=`` Sturm bound ``+ 1``, ``U_q`` included, ``T_p`` included), ``S' = T^{q-new}``,
``S'' = T^{q-old}`` (``= T_kk(1)[U_q]``), ``m = m_f`` the maximal ideal of the ``q``-new form ``f`` congruent to the
level-one eigenform ``g`` of weight ``k`` (``T_l = a_l(g) mod p`` for ``l != q, p``).  ``kk = k`` and ``kk = k + (p-1)``.

* ``eta_f(q)  = eta(S_m, lam_f)``   (full algebra; ``ord["eta"]``),
* ``eta_f(1, q) = eta(S'_m, lam_f)`` (``q``-new quotient; ``= eta^new``; ``ord["eta_new"]``),
* ``c_q(f) = lam_f(b)``, ``b = ker(S -> S'')`` (``ord["c"]``),
* ``thm_E_identity``: ``ord eta == ord c + ord eta_new`` (PYCHK acceptance; *proved* when ``S_m`` Gorenstein and
  ``O_v`` a DVR, both recorded),
* ranks of ``S_m``, ``S'_m``, ``S''_m`` (``rk_new_ge_2`` = ``rank S'_m >= 2``), the residue of ``T_p`` at ``m``
  (``ordinary`` iff it is nonzero), ``t_f(q) = v_p(a_q(g)^2 - q^{k-2}(q+1)^2)`` at ``kk = k``.

Reduction (exact, used at every weight).  Let ``A = sum c_l T_l`` (``l != q, p``) plus ``c_q U_q`` be generic (its
characteristic polynomial on the integral lattice ``L`` squarefree, checked) and keep the ``Q``-irreducible factors
``phi`` of ``charpoly(A)`` with a root ``a + c_q u`` mod ``p`` (``a`` the residue of the ``T_l``-part at ``m``,
``u = +-q^{(kk-2)/2}``: every eigensystem in ``m`` has the ``U_q``-residue of the ``q``-new form ``f``).  ``W = L cap ker prod phi(A)`` (saturated) contains the ``m``-part ``L (x) Z_p e_m``, so the image
``S_W`` of ``S`` in ``End(W)`` satisfies ``(S_W)_m = S_m``; likewise for ``W cap L^{new}``, ``W cap L^{old}``.  The
kept new factors are the Galois orbits of newforms that can meet ``m`` (each a representation ``o<i>``; ``O`` = its Hecke
order, ``lam_f`` the quotient map).  The cross-check ``reduced == full`` at one weight-``k`` triple is a test.

At ``kk = k + (p-1)``: no Gorenstein or perfectness input is assumed; ``S_m`` is tested for Gorenstein, and the
ordinary component (``T_p`` unit) is compared with Hida control (``rank`` equal to the rank at ``k``).
"""

from __future__ import annotations

