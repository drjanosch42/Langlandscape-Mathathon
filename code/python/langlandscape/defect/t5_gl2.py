TRIPLES = ((13, 18, 19), (5, 18, 23), (5, 16, 31), (13, 12, 31), (3, 18, 53), (3, 18, 61), (13, 16, 101))


def vp(x: int, p: int) -> int | str:
    if x == 0:
        return "inf"
    v = 0
    while x % p == 0:
        x //= p
        v += 1
    return v


def level_one_eigenform(k: int, ells: Sequence[int]) -> dict[int, int]:
    """``a_l(g)`` for the unique normalised eigenform ``g`` of ``S_k(SL_2(Z))`` (asserts ``dim = 1``)."""
    P = get_pari()
    mf = P.mfinit([1, k], 1)
    assert int(P.mfdim(mf)) == 1, f"S_{k}(1) is not one-dimensional"
    B = max(ells)
    c = P.mfcoefs(P.mfeigenbasis(mf)[0], B)
    return {int(l): int(c[int(l)]) for l in ells}


def _charpoly_A(full: dict, coeffs: dict[str, int], n: int):
    P = get_pari()
    A = P.matrix(n, n)
    for g, c in coeffs.items():
        A = A + c * ha.pmat(full[g], n, n)
    return A, P.charpoly(A)


def _poly_has_root_mod_p(phi, vals: list[int], p: int) -> bool:
    P = get_pari()
    return any(int(P.lift(P.subst(phi, "x", P.Mod(v, p)))) == 0 for v in vals)


def reduced_algebra(q: int, kk: int, p: int, resid: dict[str, int], seed: int = 1, max_tries: int = 6) -> dict:
    """The reduced Hecke algebra ``S_W`` (see the module docstring) with reps ``new``, ``old``, ``o<i>``.

    ``resid``: residues mod ``p`` of the ``T_l`` (``l != q, p``) at ``m``.  Returns ``{"T", "orbits", "dims", ...}``.
    """
    P = get_pari()
    ns = sorted(set(ha.hecke_generators(q, kk)) | {p, q})
    D = ha.mf_qnew_qold(q, kk, q, ns=ns, orbits=False)
    full = D["full"]
    n = D["dims"]["full"]
    Wnew_all = ha.pcols(D["bases"]["new"], n)
    rng = random.Random(seed)
    names = [f"T{l}" for l in ns if l not in (p, q)]
    for _ in range(max_tries):
        co = {g: rng.randrange(1, 50) for g in names}
        co[f"T{q}"] = rng.randrange(1, 50)
        A, cp = _charpoly_A(full, co, n)
        if int(P.issquarefree(cp)):
            break
    else:
        raise RuntimeError("no squarefree generic operator found")
    a = sum(co[g] * resid[g] for g in names) % p
    # every eigensystem in m has the U_q residue of the q-new form f: a_q(f) = +-q^{(kk-2)/2}
    uq = pow(q, (kk - 2) // 2, p)
    vals = [(a + co[f"T{q}"] * u) % p for u in (uq, -uq)]
    fac = P.factor(cp)
    kept = []
    for i in range(int(P.matsize(fac)[0])):
        phi = fac[0][i]
        if _poly_has_root_mod_p(phi, vals, p):
            K = P.matker(P.subst(phi, "x", A))
            cols = ha.mat_cols(P.mathnf(P.matrixqz(K, -2)))
            is_new = int(P.matrank(P.matconcat([Wnew_all, ha.pcols(cols, n)]))) == Wnew_all.ncols()
            kept.append({"phi": phi, "degree": int(P.poldegree(phi)), "cols": cols, "new": is_new})

    def sat(cols):
        if not cols:
            return []
        return ha.mat_cols(P.mathnf(P.matrixqz(ha.pcols(cols, n), -2)))

    W = sat([c for o in kept for c in o["cols"]])
    Wn = sat([c for o in kept if o["new"] for c in o["cols"]])
    Wo = sat([c for o in kept if not o["new"] for c in o["cols"]])
    gens = ha._restrict(full, W, n)
    nW = len(W)

    def coords(cols):  # coordinates of sublattices of W in the basis W (for _restrict on the W-lattice)
        if not cols:
            return []
        Y = P.matinverseimage(ha.pcols(W, n), ha.pcols(cols, n))
        assert P.denominator(Y) == 1
        return ha.mat_cols(Y)

    reps = {"new": ha._restrict(gens, coords(Wn), nW) if Wn else {g: [] for g in gens},
            "old": ha._restrict(gens, coords(Wo), nW) if Wo else {g: [] for g in gens}}
    orbits = []
    for o in kept:
        if o["new"]:
            name = f"o{len(orbits)}"
            reps[name] = ha._restrict(gens, coords(o["cols"]), nW)
            orbits.append({"rep": name, "degree": o["degree"]})
    T = ha.HeckeAlgebra(gens, reps, name=f"T_{kk}({q})_W")
    return {"T": T, "orbits": orbits, "dims": {**D["dims"], "W": nW, "W_new": len(Wn), "W_old": len(Wo)},
            "old_factor_degrees": [o["degree"] for o in kept if not o["new"]], "generators": ns}


def _matching_ideals(T, p: int, resid: dict[str, int]):
    """Maximal ideals of ``T`` over ``p`` with residue degree 1 and the given ``T_l`` residues."""
    out = []
    for m in T.maximal_ideals(p):
        if m.residue_degree == 1 and all(m.values.get(g) == r % p for g, r in resid.items()):
            out.append(m)
    return out


def gl2_side(q: int, k: int, p: int, kk: int | None = None) -> dict:
    """All C4 invariants for the triple ``(q, k, p)`` at weight ``kk`` (default ``k``)."""
    kk = k if kk is None else kk
    t0 = time.perf_counter()
    ns = sorted(set(ha.hecke_generators(q, kk)) | {p, q})
    g = level_one_eigenform(k, ns)
    resid = {f"T{l}": g[l] % p for l in ns if l not in (p, q)}
    R = reduced_algebra(q, kk, p, resid)
    T = R["T"]
    a, b = T.kernel_of_rep("new"), T.kernel_of_rep("old")
    Sn, qn = T.quotient(a, name="T'")
    So, qo = T.quotient(b, name="T''")
    out = {"q": q, "k": k, "p": p, "weight": kk, "dims": R["dims"], "orbit_degrees": [o["degree"] for o in R["orbits"]],
           "old_factor_degrees": R["old_factor_degrees"], "hecke_generators": R["generators"], "components": []}
    if kk == k:
        out["t_f_q"] = vp(g[q] ** 2 - q ** (k - 2) * (q + 1) ** 2, p)
        out["a_p_g_mod_p"] = g[p] % p if p in g else None
    for m in _matching_ideals(T, p, resid):
        mn, mo = ha.push_max_ideal(m, qn), ha.push_max_ideal(m, qo)
        Tp = m.values.get(f"T{p}")
        comp = {"m": m.describe(), "T_p_residue": Tp, "ordinary": Tp not in (0, None),
                "U_q_residue": m.values.get(f"T{q}"),
                "ranks": {"S_m": m.local_rank, "S_new_m": mn.local_rank if mn else 0,
                          "S_old_m": mo.local_rank if mo else 0},
                "forms": []}
        comp["rk_new_ge_2"] = comp["ranks"]["S_new_m"] >= 2
        comp["rk_full_ge_2"] = comp["ranks"]["S_m"] >= 2
        if mn is None:
            comp["note"] = "no q-new form in m"
            out["components"].append(comp)
            continue
        for o in R["orbits"]:
            chi = Character.from_rep(T, o["rep"])
            try:
                v = chi.place(m)
            except ValueError as err:
                if "does not factor" in str(err):      # mu(e_m) = 0: this orbit does not meet m
                    continue
                raise                                  # several places of O over m: not handled, never silent
            pinfo = place_info(v)
            row = {"orbit_degree": o["degree"], "place": {kx: str(x) if not isinstance(x, (int, bool)) else x
                                                          for kx, x in pinfo.items()}}
            if not pinfo["dvr"]:
                row["status"] = "not computed: O_v not a DVR (needs the maximal order via Character.from_values)"
            else:
                r = defect(T, chi, m)
                row.update({"ord": r["ord"], "thm_E_identity": r["thm_E_identity"], "gorenstein": r["gorenstein"],
                            "lemma_D": r["lemma_D"], "congruence_module_length": r["congruence_module_length"]})
            comp["forms"].append(row)
        out["components"].append(comp)
    out["runtime_s"] = round(time.perf_counter() - t0, 2)
    return out


def compute_all(triples=TRIPLES, shifted: bool = True, skip_shifted: Sequence[tuple] = ()) -> dict:
    rows = {}
    for (q, k, p) in triples:
        key = f"{q},{k},{p}"
        rows[key] = {"k": gl2_side(q, k, p)}
        if shifted:
            if (q, k, p) in skip_shifted:
                rows[key]["k+p-1"] = {"status": "not computed", "weight": k + p - 1,
                                      "reason": SKIP_REASON.get((q, k, p), "infeasible within the runtime budget")}
            else:
                try:
                    rows[key]["k+p-1"] = gl2_side(q, k, p, k + p - 1)
                except PariError as err:      # recorded, never silent: the identity is not claimed there
                    rows[key]["k+p-1"] = {"status": "not computed", "weight": k + p - 1,
                                          "reason": f"PARI error with a {STACK_BYTES >> 30} GiB stack: "
                                                    f"{str(err)[:200]}"}
    return rows


_HNF13 = ("not computed within the runtime budget: the exact HNF closure of the Hecke algebra (S06-C1 toolkit, "
          "hecke_alg._closure) at level 13 and weight {w} raised a PARI stack error with 4 GiB and was still running "
          "after 13 min (8 GiB resident) with 12 GiB (measured at (13, 36); weight {w} is at least as large)")
SKIP_REASON: dict[tuple, str] = {
    (13, 18, 19): _HNF13.format(w=36),
    (13, 12, 31): _HNF13.format(w=42) + "; mf_integral_hecke alone takes ~3 min at weight 42",
    (13, 16, 101): "not feasible here: weight 116, dim S_116(Gamma_0(13)) = 135, Hecke generators T_l up to l = 137; "
                   "mf_integral_hecke (exact integral lattice, PARI matrixqz) raised a PARI error with a 1 GiB stack, "
                   "and the HNF closure already fails at weight 36",
}
STACK_BYTES = 4 << 30   # PARI stack for k + (p-1) (1 GiB overflows in the HNF closure at (3, 78))


def _all_identities(rows: dict) -> bool:
    ok = True
    for r in rows.values():
        for w in r.values():
            for c in w.get("components", []):
                for f in c["forms"]:
                    if "thm_E_identity" in f:
                        ok = ok and f["thm_E_identity"]
    return ok


def main() -> None:  # pragma: no cover - script entry point
    """Write ``code/results/s06/T5_gl2.json``."""
    from .. import results
    get_pari().allocatemem(STACK_BYTES)
    skip = tuple(SKIP_REASON)
    with results.Timer() as tm:
        rows = compute_all(skip_shifted=skip)
    data = {"triples": rows, "all_thm_E_identities_hold": _all_identities(rows),
            "conventions": {"S": "full T_kk(Gamma_0(q)) incl. U_q and T_p (reduced to W, exact, see module docstring)",
                            "eta": "eta_f(q) = eta(S_m, lam_f), base change to O (Kim-Ota/Hsieh convention)",
                            "eta_new": "eta_f(1,q) = eta(S'_m, lam_f), S' = q-new quotient",
                            "c": "c_q(f) = lam_f(ker(S -> S''))", "ord": "ord_varpi at the place v of O over m",
                            "t_f_q": "v_p(a_q(g)^2 - q^(k-2)(q+1)^2), g level one weight k",
                            "status": "computed"}}
    path = results.write("s06/T5_gl2.json", data, script="code/python/langlandscape/defect/t5_gl2.py",
                         params={"triples": [list(t) for t in TRIPLES], "weights": ["k", "k+p-1"],
                                 "skipped_shifted": [list(t) for t in skip], "seed": 1},
                         runtime_s=round(tm.seconds, 2),
                         notes="S06-C4: T5 GL2 side; exact Hecke algebras (S06-C1 toolkit), PYCHK eta = c * eta_new")
    print(path)


if __name__ == "__main__":  # pragma: no cover
    main()
