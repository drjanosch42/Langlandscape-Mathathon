"""S06-C1: commutative ``Z``-orders (Hecke algebras) from integer matrices; maximal ideals over ``p``; localisation.

Tex: ``plan/staged/stage-06-integral-defect.tex`` (``def:s06-rings``, ``ss:s06-ca``).  API overview and the maths
conventions: :mod:`langlandscape.defect.congruence` (module docstring).

Design (exact global, rigorous local)
-------------------------------------
* A :class:`ZOrder` is a commutative ring that is free of rank ``d`` over ``Z``, given by structure constants
  (``L[i]`` = matrix of multiplication by the basis element ``e_i``; column ``j`` = coordinates of ``e_i e_j``).
  Its ``p``-adic completion is ``S (x) Z_p = prod_m S_m``.
* Ideals (:class:`ZIdeal`) are ``Z``-lattices in ``Z^d`` in HNF.  Sums, products, intersections, annihilators,
  kernels and images are computed **exactly over Z** (PARI ``mathnf`` / ``matker`` + ``matrixqz``).  Kernels and
  annihilators are saturated, so they commute with ``(x) Z_p`` and with localisation.
* Localisation at a maximal ideal ``m`` over ``p`` (:class:`MaxIdeal`) uses the idempotent ``e_m``: it is found mod ``p``
  by Berlekamp (the Frobenius ``x -> x^p`` is ``F_p``-linear on ``S/p``; its fixed points are the span of the
  idempotents) and lifted to ``Z/p^M`` by ``e <- 3e^2 - 2e^3``.  :func:`local_length` measures ``length_{Z_p}
  (X/Y)_m`` for ideals ``Y <= X``; the working precision ``M`` is chosen from the exact global elementary divisors of
  ``Y`` in ``X``, so the result is exact (not a precision guess).  Smith forms use PARI ``matsnf`` via the stage-03
  helper :func:`langlandscape.ribet.graphs.smith_divisors`.
* :class:`HeckeAlgebra` is the ``Z``-subalgebra of ``End(V)`` generated by integer matrices (closure under the
  generators, HNF), together with named further representations (``q``-new / ``q``-old / an eigenform orbit),
  carried along block-diagonally so that ``ker(T -> End V_rho)`` is exact.
* :func:`mf_integral_hecke` / :func:`mf_qnew_qold`: integral Hecke matrices of PARI's ``S_k(Gamma_0(N))`` on the
  lattice of forms with integral ``q``-expansion, and its ``q``-new / ``q``-old sublattices.
"""

