# ------------------------------------------------------------------------------------------------ PARI helpers

def _P():
    return get_pari()


def pmat(rows: Sequence[Sequence[int]], nrows: int | None = None, ncols: int | None = None):
    """PARI matrix from a list of rows."""
    nrows = len(rows) if nrows is None else nrows
    ncols = (len(rows[0]) if rows else 0) if ncols is None else ncols
    return _P().matrix(nrows, ncols, [x for r in rows for x in r])


def pcols(cols: Sequence[Sequence[int]], nrows: int):
    """PARI matrix whose columns are ``cols``."""
    return _P().matrix(len(cols), nrows, [x for c in cols for x in c]).mattranspose()


def mat_cols(M) -> list[list[int]]:
    """Columns of a PARI integer matrix as Python lists."""
    return [[int(x) for x in M[j]] for j in range(M.ncols())]


def mat_rows(M) -> list[list[int]]:
    return [[int(M[i, j]) for j in range(M.ncols())] for i in range(M.nrows())]


def _hnf_cols(cols: list[list[int]], d: int) -> list[list[int]]:
    """HNF basis (columns) of the Z-span of ``cols`` in ``Z^d``."""
    cols = [c for c in cols if any(c)]
    if not cols:
        return []
    return mat_cols(_P().mathnf(pcols(cols, d)))


def _sat_kernel(A, ncols: int) -> list[list[int]]:
    """Saturated integer kernel ``{x in Z^ncols : A x = 0}`` (columns, HNF).  ``A`` is a PARI matrix or ``None``."""
    P = _P()
    if A is None or A.nrows() == 0:
        return [[int(i == j) for i in range(ncols)] for j in range(ncols)]
    K = P.matker(A)
    if K.ncols() == 0:
        return []
    return mat_cols(P.mathnf(P.matrixqz(K, -2)))


def _coords(basis_cols: list[list[int]], vecs: list[list[int]], d: int) -> list[list[int]]:
    """Integer coordinates of ``vecs`` in the lattice basis ``basis_cols``; raises if not in the lattice."""
    if not vecs:
        return []
    if not basis_cols:
        if any(any(v) for v in vecs):
            raise ValueError("vector not in the zero lattice")
        return [[] for _ in vecs]
    P = _P()
    X = P.matinverseimage(pcols(basis_cols, d), pcols(vecs, d))
    if X.ncols() != len(vecs) or P.denominator(X) != 1:
        raise ValueError("vectors are not in the lattice spanned by the basis")
    return mat_cols(X)


def vp(n: int, p: int) -> int | float:
    """``p``-adic valuation of an integer (``inf`` for 0)."""
    n = abs(int(n))
    if n == 0:
        return float("inf")
    v = 0
    while n % p == 0:
        n //= p
        v += 1
    return v


# ------------------------------------------------------------------------------------------------ linear algebra mod q

def _rref_mod_p(A: np.ndarray, p: int) -> tuple[np.ndarray, list[int]]:
    """Reduced row echelon form of ``A`` over ``F_p`` (object array) and the pivot columns."""
    A = np.array(A, dtype=object) % p
    nr, nc = A.shape
    piv: list[int] = []
    r = 0
    for c in range(nc):
        if r == nr:
            break
        nz = [i for i in range(r, nr) if A[i, c] % p]
        if not nz:
            continue
        i = nz[0]
        A[[r, i]] = A[[i, r]]
        A[r] = (A[r] * pow(int(A[r, c]), -1, p)) % p
        for i2 in range(nr):
            if i2 != r and A[i2, c] % p:
                A[i2] = (A[i2] - A[i2, c] * A[r]) % p
        piv.append(c)
        r += 1
    return A[:r], piv


def _kernel_mod_p(A: np.ndarray, p: int, ncols: int | None = None) -> list[np.ndarray]:
    """Basis of ``{x in F_p^n : A x = 0}``."""
    A = np.array(A, dtype=object)
    n = A.shape[1] if A.ndim == 2 and A.size else (ncols or 0)
    if A.size == 0:
        return [np.array([int(i == j) for i in range(n)], dtype=object) for j in range(n)]
    R, piv = _rref_mod_p(A, p)
    free = [c for c in range(n) if c not in piv]
    out = []
    for f in free:
        x = np.zeros(n, dtype=object)
        x[f] = 1
        for r, c in enumerate(piv):
            x[c] = (-R[r, f]) % p
        out.append(x)
    return out


def _colspace_mod_p(cols: list[np.ndarray], p: int, n: int) -> list[np.ndarray]:
    """A basis of the ``F_p``-span of ``cols`` (as vectors of length ``n``)."""
    if not cols:
        return []
    R, _ = _rref_mod_p(np.array([list(c) for c in cols], dtype=object), p)
    return [np.array(r, dtype=object) for r in R]


def _rank_mod_p(cols: list[np.ndarray], p: int) -> int:
    if not cols:
        return 0
    return len(_rref_mod_p(np.array([list(c) for c in cols], dtype=object), p)[1])


# ------------------------------------------------------------------------------------------------ orders

class ZOrder:
    """Commutative ring free of rank ``d`` over ``Z`` with basis ``e_0..e_{d-1}``.

    ``L[i]`` (PARI ``d x d``) is multiplication by ``e_i``; ``one`` the coordinates of ``1``; ``gens`` named elements
    that generate the ring (default: the basis).  Elements are coordinate lists of Python ints.
    """

    def __init__(self, L: list, one: list[int], gens: dict[str, list[int]] | None = None, name: str = "S"):
        self.L = L
        self.d = len(L)
        self.one = [int(x) for x in one]
        self.gens = dict(gens) if gens else {f"e{i}": [int(i == j) for j in range(self.d)] for i in range(self.d)}
        self.name = name
        self._Lmod: dict[int, np.ndarray] = {}
        self._maxideals: dict[int, list[MaxIdeal]] = {}

    # -- construction
    @classmethod
    def from_table(cls, table: Sequence[Sequence[Sequence[int]]], one: list[int],
                   gens: dict[str, list[int]] | None = None, name: str = "S") -> "ZOrder":
        """``table[i][j]`` = coordinates of ``e_i e_j``."""
        d = len(table)
        L = [pcols([list(table[i][j]) for j in range(d)], d) for i in range(d)]
        O = cls(L, one, gens, name)
        O.check()
        return O

    @classmethod
    def integers(cls) -> "ZOrder":
        """The order ``Z`` (rank 1)."""
        return cls([pmat([[1]])], [1], {"1": [1]}, name="Z")

    @classmethod
    def from_polynomial(cls, coeffs: Sequence[int], name: str = "O") -> "ZOrder":
        """``Z[x]/(g)`` for monic ``g`` (coefficients leading first), basis ``1, x, .., x^{n-1}``; generator ``x``."""
        c = [int(a) for a in coeffs]
        assert c[0] == 1, "g must be monic"
        n = len(c) - 1
        comp = [[0] * n for _ in range(n)]          # multiplication by x (columns: x * x^j)
        for j in range(n - 1):
            comp[j + 1][j] = 1
        for i in range(n):
            comp[i][n - 1] = -c[n - i]
        X = pmat(comp)
        L = [_P().matid(n)]
        for _ in range(1, n):
            L.append(L[-1] * X)
        O = cls(L, [int(i == 0) for i in range(n)], {"x": [int(i == 1) for i in range(n)]} if n > 1
                else {"x": [-c[1]]}, name)
        return O

    def check(self) -> None:
        """Assert commutativity, associativity and the identity on basis elements."""
        d = self.d
        P = _P()
        one = P.Col(self.one)
        for i in range(d):
            assert self.L[i] * one == P.Col([int(i == j) for j in range(d)]), "identity"
            for j in range(d):
                assert self.L[i][j] == self.L[j][i], "commutativity"
                # e_i (e_j e_k) = (e_i e_j) e_k  <=>  L_i L_j = L(e_i e_j)
                assert self.L[i] * self.L[j] == self.lmat(mat_cols(pcols([list(map(int, self.L[i][j]))], d))[0]), \
                    "associativity"

    # -- arithmetic
    def lmat(self, x: Sequence[int]):
        """PARI matrix of multiplication by ``x``."""
        P = _P()
        M = P.matrix(self.d, self.d)
        for i, c in enumerate(x):
            if c:
                M = M + int(c) * self.L[i]
        return M

    def mul(self, x: Sequence[int], y: Sequence[int]) -> list[int]:
        return [int(v) for v in self.lmat(x) * _P().Col([int(c) for c in y])]

    def add(self, *xs: Sequence[int]) -> list[int]:
        return [sum(int(x[i]) for x in xs) for i in range(self.d)]

    def scale(self, a: int, x: Sequence[int]) -> list[int]:
        return [int(a) * int(c) for c in x]

    def sub(self, x, y) -> list[int]:
        return [int(a) - int(b) for a, b in zip(x, y)]

    def power(self, x: Sequence[int], n: int) -> list[int]:
        r, b = list(self.one), list(x)
        while n:
            if n & 1:
                r = self.mul(r, b)
            b = self.mul(b, b)
            n >>= 1
        return r

    def gen(self, name: str) -> list[int]:
        return list(self.gens[name])

    def scalar(self, a: int) -> list[int]:
        return self.scale(a, self.one)

    def poly(self, coeffs: Sequence[int], x: Sequence[int]) -> list[int]:
        """``g(x)`` for ``g`` with integer coefficients, leading first."""
        r = [0] * self.d
        for c in coeffs:
            r = self.add(self.mul(r, x), self.scalar(c))
        return r

    def basis_vec(self, i: int) -> list[int]:
        return [int(i == j) for j in range(self.d)]

    # -- ideals
    def whole(self) -> "ZIdeal":
        return ZIdeal(self, [self.basis_vec(i) for i in range(self.d)])

    def zero_ideal(self) -> "ZIdeal":
        return ZIdeal(self, [])

    def ideal(self, elements: Iterable[Sequence[int]]) -> "ZIdeal":
        """The ideal generated by ``elements``."""
        cols: list[list[int]] = []
        for x in elements:
            cols.extend(mat_cols(self.lmat(x)))
        return ZIdeal(self, _hnf_cols(cols, self.d))

    def submodule(self, vectors: Iterable[Sequence[int]], check_ideal: bool = True) -> "ZIdeal":
        """The ``Z``-span of ``vectors`` (asserted to be an ideal unless ``check_ideal=False``)."""
        I = ZIdeal(self, _hnf_cols([list(map(int, v)) for v in vectors], self.d))
        if check_ideal:
            assert self.ideal(I.basis) == I, "submodule is not an ideal"
        return I

    def quotient(self, I: "ZIdeal", name: str | None = None) -> tuple["ZOrder", "ZHom"]:
        """``S/I`` for a saturated ideal ``I`` (so ``S/I`` is ``Z``-free), with the quotient map."""
        assert I.order is self
        if not I.is_saturated():
            raise ValueError("quotient needs a saturated ideal (S/I must be Z-free)")
        P = _P()
        d, a = self.d, I.rank
        if a == 0:
            Q = P.matid(d)
        else:
            F = _sat_kernel(pcols(I.basis, d).mattranspose(), d)     # functionals vanishing on I (columns)
            if not F:
                O = ZOrder([], [], {}, name or f"{self.name}/I")
                return O, ZHom(self, O, None)
            Q = pcols(F, d).mattranspose()                            # (d-a) x d, surjective, kernel I
        H, U = P.mathnf(Q, 1)
        n = d - a
        assert H == P.matid(n), "quotient map not surjective"
        R = P.matrix(d, n, [U[i, j] for i in range(d) for j in range(U.ncols() - n, U.ncols())])
        # R: lifts of the quotient basis (Q R = I_n)
        assert Q * R == P.matid(n)
        L = [Q * self.lmat(mat_cols(R)[k]) * R for k in range(n)]
        one = [int(v) for v in Q * P.Col(self.one)]
        gens = {k: [int(v) for v in Q * P.Col(g)] for k, g in self.gens.items()}
        O = ZOrder(L, one, gens, name or f"{self.name}/I")
        h = ZHom(self, O, Q)
        h.section = R          # lifts of the basis of S/I (PARI d x (d-a)), Q R = 1
        return O, h

    # -- tensor with another order (lazy multiplication matrices)
    def L_mod(self, q: int) -> np.ndarray:
        """``(d, d, d)`` object array of the ``L[i]`` reduced mod ``q``."""
        if q not in self._Lmod:
            arr = np.zeros((self.d, self.d, self.d), dtype=object)
            for i in range(self.d):
                arr[i] = np.array(mat_rows(self.L[i]), dtype=object) % q
            self._Lmod[q] = arr
        return self._Lmod[q]

    def mul_mod(self, x, y, q: int) -> np.ndarray:
        Lq = self.L_mod(q)
        x = np.array(x, dtype=object) % q
        y = np.array(y, dtype=object) % q
        M = np.tensordot(x, Lq, axes=1) % q
        return M.dot(y) % q

    def lmat_mod(self, x, q: int) -> np.ndarray:
        return np.tensordot(np.array(x, dtype=object) % q, self.L_mod(q), axes=1) % q

    def pow_mod(self, x, n: int, q: int) -> np.ndarray:
        r = np.array(self.one, dtype=object) % q
        b = np.array(x, dtype=object) % q
        while n:
            if n & 1:
                r = self.mul_mod(r, b, q)
            b = self.mul_mod(b, b, q)
            n >>= 1
        return r

    def maximal_ideals(self, p: int) -> list["MaxIdeal"]:
        return maximal_ideals(self, p)

    def __repr__(self) -> str:
        return f"ZOrder({self.name}, rank {self.d}, gens {list(self.gens)})"


@dataclass
class ZIdeal:
    """``Z``-lattice in an order (normally an ideal); ``basis`` = HNF columns."""

    order: ZOrder
    basis: list[list[int]]

    def __post_init__(self) -> None:
        self.basis = [list(map(int, b)) for b in self.basis]

    @property
    def rank(self) -> int:
        return len(self.basis)

    def _pm(self):
        return pcols(self.basis, self.order.d)

    def __eq__(self, other: object) -> bool:
        return isinstance(other, ZIdeal) and other.order is self.order and self.basis == other.basis

    def __add__(self, other: "ZIdeal") -> "ZIdeal":
        return ZIdeal(self.order, _hnf_cols(self.basis + other.basis, self.order.d))

    def __mul__(self, other: "ZIdeal") -> "ZIdeal":
        cols = [self.order.mul(x, y) for x in self.basis for y in other.basis]
        return ZIdeal(self.order, _hnf_cols(cols, self.order.d))

    def contains(self, x: Sequence[int]) -> bool:
        if not any(x):
            return True
        try:
            _coords(self.basis, [list(x)], self.order.d)
            return True
        except ValueError:
            return False

    def __le__(self, other: "ZIdeal") -> bool:
        return all(other.contains(b) for b in self.basis)

    def intersect(self, other: "ZIdeal") -> "ZIdeal":
        if not self.basis or not other.basis:
            return ZIdeal(self.order, [])
        d = self.order.d
        A = pcols(self.basis + [[-x for x in b] for b in other.basis], d)
        K = _sat_kernel(A, self.rank + other.rank)
        cols = [[sum(k[j] * self.basis[j][i] for j in range(self.rank)) for i in range(d)] for k in K]
        return ZIdeal(self.order, _hnf_cols(cols, d))

    def ann(self) -> "ZIdeal":
        """``Ann_S(I)`` (saturated)."""
        S = self.order
        if not self.basis:
            return S.whole()
        P = _P()
        A = P.matconcat(P.Col([S.lmat(x) for x in self.basis]))   # vertical stack
        return ZIdeal(S, _sat_kernel(A, S.d))

    def is_saturated(self) -> bool:
        return self.saturation() == self

    def saturation(self) -> "ZIdeal":
        if not self.basis:
            return self
        return ZIdeal(self.order, mat_cols(_P().mathnf(_P().matrixqz(self._pm(), -2))))

    def divisors_in(self, other: "ZIdeal") -> tuple[list[int], int]:
        """Elementary divisors of ``self`` inside ``other`` (``self <= other``): (nonzero divisors, free rank of
        ``other/self``)."""
        C = _coords(other.basis, self.basis, self.order.d)
        if not C:
            return [], other.rank
        divs = smith_divisors(mat_rows(pcols(C, other.rank)), other.rank, len(C))
        return divs, other.rank - len(divs)

    def index_in(self, other: "ZIdeal") -> int | float:
        divs, free = self.divisors_in(other)
        if free:
            return float("inf")
        out = 1
        for x in divs:
            out *= x
        return out

    def __repr__(self) -> str:
        return f"ZIdeal(rank {self.rank} in {self.order.name})"


@dataclass
class ZHom:
    """Additive (normally ring) map ``src -> tgt`` with PARI matrix ``A`` (``tgt.d x src.d``).

    ``tgt`` is a :class:`ZOrder`, or an ``int`` (target ``Z^n``; used for representations ``S -> End(V)``).
    """

    src: ZOrder
    tgt: "ZOrder | int"
    A: object

    @property
    def tdim(self) -> int:
        return self.tgt if isinstance(self.tgt, int) else self.tgt.d

    def __call__(self, x: Sequence[int]) -> list[int]:
        if self.tdim == 0:
            return []
        return [int(v) for v in self.A * _P().Col([int(c) for c in x])]

    def kernel(self) -> ZIdeal:
        if self.tdim == 0:
            return self.src.whole()
        return ZIdeal(self.src, _sat_kernel(self.A, self.src.d))

    def image(self, I: ZIdeal, as_ideal: bool = True) -> ZIdeal:
        """``phi(I)``; with ``as_ideal`` the ideal of ``tgt`` it generates."""
        assert isinstance(self.tgt, ZOrder)
        imgs = [self(b) for b in I.basis]
        return self.tgt.ideal(imgs) if as_ideal else ZIdeal(self.tgt, _hnf_cols(imgs, self.tgt.d))

    def compose(self, other: "ZHom") -> "ZHom":
        """``self o other``."""
        return ZHom(other.src, self.tgt, self.A * other.A)

    def check_ring_hom(self) -> None:
        S, O = self.src, self.tgt
        assert isinstance(O, ZOrder)
        assert self(S.one) == O.one, "phi(1) != 1"
        for i in range(S.d):
            for j in range(i, S.d):
                assert self(S.mul(S.basis_vec(i), S.basis_vec(j))) == O.mul(self(S.basis_vec(i)),
                                                                              self(S.basis_vec(j))), "not multiplicative"


# ------------------------------------------------------------------------------------------------ Hecke algebras

def _closure(gen_blocks: list[tuple], sizes: list[int], max_iter: int = 500):
    """Z-basis (HNF, flattened block-diagonal columns) of the ring generated by ``gen_blocks``."""
    P = _P()
    flatf = P("(M)->concat(Vec(M~))")
    offs = [0]
    for n in sizes:
        offs.append(offs[-1] + n * n)
    D = offs[-1]

    def vec(e):
        return P.concat([flatf(b) for b in e]) if len(e) > 1 else flatf(e[0])

    def unvec(v):
        return tuple(P.matrix(n, n, [v[offs[b] + t] for t in range(n * n)]) for b, n in enumerate(sizes))

    ident = tuple(P.matid(n) for n in sizes)
    H = P.mathnf(P.matconcat([vec(ident)] + [vec(g) for g in gen_blocks]))
    for _ in range(max_iter):
        basis = [unvec(H[k]) for k in range(H.ncols())]
        prods = [vec(tuple(bb * gb for bb, gb in zip(b, g))) for b in basis for g in gen_blocks]
        H2 = P.mathnf(P.matconcat([H] + prods)) if prods else H
        if H2 == H:
            return H, offs, D
        H = H2
    raise RuntimeError("closure did not stabilise")


class HeckeAlgebra(ZOrder):
    """The ``Z``-algebra generated by commuting integer matrices ``gens[name]`` on ``V = Z^n``.

    ``reps[rho][name]`` are the matrices of the same generators on further lattices ``V_rho`` (``q``-new, ``q``-old,
    an eigenform orbit, ...).  Each ``V_rho (x) Q`` must be a subquotient of ``V (x) Q`` (checked: the joint algebra
    has the same rank), so ``T -> End(V_rho)`` is well defined and :meth:`kernel_of_rep` is ``ker(T -> T_rho)``.
    """

    def __init__(self, gens: dict[str, Sequence[Sequence[int]]],
                 reps: dict[str, dict[str, Sequence[Sequence[int]]]] | None = None, name: str = "T"):
        P = _P()
        self.gen_names = list(gens)
        self.rep_names = list(reps or {})
        reps = reps or {}
        n = len(next(iter(gens.values())))
        rsize = {r: len(next(iter(reps[r].values()))) if reps[r] else 0 for r in self.rep_names}
        for r in self.rep_names:
            assert set(reps[r]) == set(gens), f"rep {r}: generator names differ"
        live = [r for r in self.rep_names if rsize[r] > 0]          # zero-dimensional reps: kernel = everything
        sizes_nz = [n] + [rsize[r] for r in live]
        blocks = [tuple([pmat(gens[g], n, n)] + [pmat(reps[r][g], rsize[r], rsize[r]) for r in live])
                  for g in self.gen_names]
        self._live = live
        H, offs, D = _closure(blocks, sizes_nz)
        d = H.ncols()
        Hmain = P.matrix(n * n, d, [H[i, j] for i in range(n * n) for j in range(d)])
        if P.matrank(Hmain) != d:
            raise ValueError("a representation is not a subquotient of the main one (joint rank > rank on V)")
        rows = [int(i) for i in P.matindexrank(Hmain)[0]]
        Bsub = P.matrix(d, d, [Hmain[i - 1, j] for i in rows for j in range(d)])
        Binv = Bsub ** -1
        self.n = n
        self.H = H
        self._offs = offs
        self._sizes = sizes_nz
        self._rows = rows
        self._Binv = Binv
        mains = [P.matrix(n, n, [H[t, k] for t in range(n * n)]) for k in range(d)]
        self._mains = mains

        def coords_of(M) -> list[int]:
            v = Binv * P.Col([M[(i - 1) // n, (i - 1) % n] for i in rows])
            assert P.denominator(v) == 1
            return [int(x) for x in v]

        self._coords_of = coords_of
        L = []
        for i in range(d):
            L.append(pcols([coords_of(mains[i] * mains[j]) for j in range(d)], d))
        one = coords_of(P.matid(n))
        gcoords = {g: coords_of(pmat(gens[g], n, n)) for g in self.gen_names}
        super().__init__(L, one, gcoords, name)

    def element_from_matrix(self, M: Sequence[Sequence[int]]) -> list[int]:
        """Coordinates of a matrix on ``V`` that lies in the algebra (raises otherwise)."""
        P = _P()
        Mp = pmat(M, self.n, self.n)
        x = self._coords_of(Mp)
        if self.matrix_of(x) != Mp:
            raise ValueError("matrix is not in the Hecke algebra")
        return x

    def matrix_of(self, x: Sequence[int]):
        """The PARI matrix of ``x`` on ``V``."""
        P = _P()
        M = P.matrix(self.n, self.n)
        for k, c in enumerate(x):
            if c:
                M = M + int(c) * self._mains[k]
        return M

    def rep_hom(self, rho: str) -> ZHom:
        """``T -> End(V_rho) = Z^{n_rho^2}`` (flattened, row-major)."""
        if rho not in self._live:
            assert rho in self.rep_names, rho
            return ZHom(self, 0, None)
        b = 1 + self._live.index(rho)
        P = _P()
        lo, hi = self._offs[b], self._offs[b + 1]
        d = self.d
        A = P.matrix(hi - lo, d, [self.H[i, j] for i in range(lo, hi) for j in range(d)]) if hi > lo else None
        return ZHom(self, hi - lo, A)

    def kernel_of_rep(self, rho: str) -> ZIdeal:
        """``ker(T -> End V_rho)`` (saturated ideal; e.g. ``a`` for the ``q``-new and ``b`` for the ``q``-old rep)."""
        return self.rep_hom(rho).kernel()

    def hom_from_values(self, O: ZOrder, values: dict[str, Sequence[int]]) -> ZHom:
        """The ring map ``T -> O`` with ``T_name -> values[name]`` (raises if no such map exists)."""
        P = _P()
        n = self.n
        mains = [self._mains_gen(g) for g in self.gen_names]
        blocks = [(mains[i], O.lmat(values[g])) for i, g in enumerate(self.gen_names)]
        H, offs, D = _closure(blocks, [n, O.d])
        if H.ncols() != self.d:
            raise ValueError("generator values do not define a ring map T -> O")
        C = pcols([self._coords_of(P.matrix(n, n, [H[t, k] for t in range(n * n)])) for k in range(self.d)], self.d)
        assert abs(P.matdet(C)) == 1
        Cinv = C ** -1
        one_O = P.Col(O.one)
        img_joint = [P.matrix(O.d, O.d, [H[offs[1] + t, k] for t in range(O.d * O.d)]) * one_O for k in range(self.d)]
        Ajoint = P.matconcat(img_joint)
        phi = ZHom(self, O, Ajoint * Cinv)
        phi.check_ring_hom()
        return phi

    def _mains_gen(self, g: str):
        return self.matrix_of(self.gens[g])


def sturm_bound(N: int, k: int) -> int:
    """``floor(k [SL_2(Z) : Gamma_0(N)] / 12)`` (classical Sturm bound; PARI's ``mfsturm`` is smaller and is not
    used for integrality)."""
    P = _P()
    idx = N
    for ell in P.primes([2, N]) if N > 1 else []:
        if N % int(ell) == 0:
            idx = idx * (int(ell) + 1) // int(ell)
    return k * idx // 12


def hecke_generators(N: int, k: int) -> list[int]:
    """Primes ``<= sturm_bound + 1``: they generate the Hecke ring of ``S_k(Gamma_0(N))`` (Z-span of
    ``T_1..T_B``)."""
    return [int(x) for x in _P().primes([2, sturm_bound(N, k) + 1])]


def _integral_lattice(C):
    """Columns of ``C`` = q-expansions of a Q-basis; returns ``X`` with ``C X`` = basis of the integral forms."""
    P = _P()
    Lam = P.matrixqz(C, -2)
    X = P.matinverseimage(C, Lam)
    assert X.ncols() == C.ncols()
    return X


def mf_integral_hecke(N: int, k: int, ns: Sequence[int] | None = None, flag: int = 1):
    """Integral Hecke matrices ``T_n`` (``U_n`` for ``n | N``) on the lattice of forms in ``mfinit([N,k],flag)``
    with integral q-expansions.  Returns ``(mats: {f"T{n}": rows}, coef_matrix)``, coef_matrix = q-expansions of the
    lattice basis (PARI matrix, ``a_0..a_B``)."""
    P = _P()
    mf = P.mfinit([N, k], flag)
    ns = list(ns) if ns is not None else hecke_generators(N, k)
    B = sturm_bound(N, k) + 2
    C = P.mfcoefs(mf, B)
    if C.ncols() == 0:
        return {f"T{n}": [] for n in ns}, C
    X = _integral_lattice(C)
    Xi = X ** -1
    out = {}
    for n in ns:
        H = Xi * P.mfheckemat(mf, n) * X
        assert P.denominator(H) == 1, f"T{n} not integral on the integral lattice"
        out[f"T{n}"] = mat_rows(H)
    return out, C * X


def _restrict(mats: dict[str, list], Wcols: list[list[int]], n: int) -> dict[str, list]:
    """Restriction of integer matrices to the saturated stable sublattice with basis ``Wcols``."""
    P = _P()
    W = pcols(Wcols, n)
    out = {}
    for g, M in mats.items():
        HW = pmat(M, n, n) * W
        Y = P.matinverseimage(W, HW)
        assert Y.ncols() == len(Wcols) and P.denominator(Y) == 1, f"{g}: sublattice not stable"
        out[g] = mat_rows(Y)
    return out


def mf_qnew_qold(N: int, k: int, q: int, ns: Sequence[int] | None = None, orbits: bool = True):
    """``S_k(Gamma_0(N))`` (trivial character, ``q || N``) on its integral lattice, with the ``q``-new and ``q``-old
    sublattices.  Returns ``{"full", "new", "old"}`` integer Hecke matrices (same generator names), dimensions, and
    ``"orbits"``: per Galois orbit of newforms of exact level ``N`` its polynomial, dimension and integer Hecke
    matrices ``"rep"`` (pass as a representation, then :meth:`Character.from_rep`).

    ``q``-old = span of ``g(z), g(qz)`` for ``g`` in ``S_k(Gamma_0(N/q))``; ``q``-new = span of ``h(dz)`` for ``h``
    new of level ``L`` with ``q | L | N``, ``d | N/L`` (Hecke-stable complement, strong multiplicity one).
    ``"bases"``: the HNF bases (columns, coordinates in the integral lattice) of the ``q``-new / ``q``-old
    sublattices.  ``orbits=False`` skips the (costly at large weight) ``mfsplit`` and returns ``"orbits": None``.
    """
    assert N % q == 0 and (N // q) % q != 0
    P = _P()
    M = N // q
    ns = list(ns) if ns is not None else hecke_generators(N, k)
    full, CL = mf_integral_hecke(N, k, ns, 1)
    nfull = CL.ncols()
    B = CL.nrows() - 1

    def expand(Cl, d):  # q-expansions f(q^d), truncated at B
        rows = [[0] * Cl.ncols() for _ in range(B + 1)]
        for i in range(0, B + 1, d):
            if i // d < Cl.nrows():
                rows[i] = [int(x) if P.denominator(x) == 1 else x for x in [Cl[i // d, j] for j in range(Cl.ncols())]]
        return rows

    old_cols, new_cols = [], []
    if M >= 1:
        mfM = P.mfinit([M, k], 1)
        CM = P.mfcoefs(mfM, B)
        for d in (1, q):
            for r in zip(*expand(CM, d)) if CM.ncols() else []:
                old_cols.append(list(r))
    for L in P.divisors(N):
        L = int(L)
        if L % q:
            continue
        mfL = P.mfinit([L, k], 0)
        CN = P.mfcoefs(mfL, B)
        if CN.ncols() == 0:
            continue
        for d in P.divisors(N // L):
            for r in zip(*expand(CN, int(d))):
                new_cols.append(list(r))

    def sub(cols):
        if not cols:
            return []
        Wq = P.matrix(len(cols), B + 1, [x for c in cols for x in c]).mattranspose()
        Y = P.matinverseimage(CL, Wq)          # coordinates in the integral lattice basis
        assert Y.ncols() == len(cols)
        S = P.matrixqz(P.matimage(Y), -2)
        return mat_cols(P.mathnf(S))

    Wold, Wnew = sub(old_cols), sub(new_cols)
    assert len(Wold) + len(Wnew) == nfull, "q-new + q-old dimensions do not add up"
    # Galois orbits of newforms of exact level N (PARI mfsplit): Q-span of the coefficient vectors of one eigenform
    orbits = [] if orbits else None
    mfN = P.mfinit([N, k], 0)
    if orbits is not None and P.mfdim(mfN):
        CNN = P.mfcoefs(mfN, B)
        vF, vK = P.mfsplit(mfN)
        for F, K in zip(vF, vK):
            deg = int(P.poldegree(K))
            cols = []
            for i in range(deg):
                w = P.Col([P.polcoef(P.lift(x), i, "y") if deg > 1 else x for x in F])
                cols.append([sum(CNN[r, j] * w[j] for j in range(len(F))) for r in range(B + 1)])
            Wf = sub(cols)
            orbits.append({"poly": str(K), "dim": len(Wf), "rep": _restrict(full, Wf, nfull)})
    return {
        "full": full,
        "new": _restrict(full, Wnew, nfull) if Wnew else {g: [] for g in full},
        "old": _restrict(full, Wold, nfull) if Wold else {g: [] for g in full},
        "dims": {"full": nfull, "new": len(Wnew), "old": len(Wold)},
        "bases": {"new": Wnew, "old": Wold},
        "orbits": orbits,
    }


# ------------------------------------------------------------------------------------------------ maximal ideals

@dataclass
class MaxIdeal:
    """A maximal ideal ``m`` of ``S`` over ``p``, given by its idempotent ``ebar`` in ``S/p``.

    ``residue_degree`` ``f = [S/m : F_p]``; ``local_rank`` = ``rank_{Z_p} S_m``; ``labels[name]`` = the irreducible
    polynomial over ``F_p`` (coefficients, leading first) of the generator ``name`` at ``m``; ``values[name]`` its
    residue when that has degree 1.
    """

    order: ZOrder
    p: int
    ebar: list[int]
    local_rank: int = 0
    residue_degree: int = 0
    labels: dict[str, list[int]] = field(default_factory=dict)
    values: dict[str, int] = field(default_factory=dict)
    _lifts: dict[int, np.ndarray] = field(default_factory=dict, repr=False)

    def idempotent(self, M: int) -> np.ndarray:
        """``e_m`` modulo ``p^M`` (object array of coordinates)."""
        if M in self._lifts:
            return self._lifts[M]
        q = self.p ** M
        S = self.order
        e = np.array(self.ebar, dtype=object) % q
        prec = 1
        while True:
            e2 = S.mul_mod(e, e, q)
            e_new = (3 * e2 - 2 * S.mul_mod(e2, e, q)) % q
            prec *= 2
            if prec >= M and all(e_new == e):
                break
            e = e_new
        assert all(S.mul_mod(e, e, q) == e)
        self._lifts[M] = e
        return e

    def ideal(self) -> ZIdeal:
        """``m`` as a global ideal: ``p S + lift((1 - ebar) S/p + rad(S/p))``."""
        S, p = self.order, self.p
        W = _complement_plus_rad(S, p, self.ebar)
        gens = [[p * int(i == j) for j in range(S.d)] for i in range(S.d)] + [[int(x) for x in w] for w in W]
        return ZIdeal(S, _hnf_cols(gens, S.d))

    def describe(self) -> dict:
        return {"p": self.p, "local_rank": self.local_rank, "residue_degree": self.residue_degree,
                "labels": self.labels, "values": self.values}


def _frobenius_matrix(S: ZOrder, p: int) -> np.ndarray:
    cols = [S.pow_mod(S.basis_vec(i), p, p) for i in range(S.d)]
    return np.array(cols, dtype=object).T % p


def _radical_mod_p(S: ZOrder, p: int) -> list[np.ndarray]:
    """Basis of the nilradical of ``S/p`` = ``ker Frob^k`` with ``p^k >= d``."""
    F = _frobenius_matrix(S, p)
    k, pk = 1, p
    while pk < S.d:
        k += 1
        pk *= p
    Fk = np.identity(S.d, dtype=object)
    for _ in range(k):
        Fk = Fk.dot(F) % p
    return _kernel_mod_p(Fk, p, S.d)


def _complement_plus_rad(S: ZOrder, p: int, ebar) -> list[np.ndarray]:
    one = np.array(S.one, dtype=object)
    f = (one - np.array(ebar, dtype=object)) % p
    comp = [S.mul_mod(f, S.basis_vec(i), p) for i in range(S.d)]
    return _colspace_mod_p(comp + _radical_mod_p(S, p), p, S.d)


def _minpoly_mod_p(S: ZOrder, x, e, p: int) -> list[int]:
    """Minimal polynomial (leading first) over ``F_p`` of ``x e`` in the algebra ``e S/p`` (identity ``e``)."""
    vecs = [np.array(e, dtype=object) % p]
    xe = S.mul_mod(x, e, p)
    while True:
        nxt = S.mul_mod(xe, vecs[-1], p)
        A = np.array([list(v) for v in vecs] + [list(nxt)], dtype=object).T
        ker = _kernel_mod_p(A, p)
        if ker:
            c = ker[0]
            lead = int(c[-1])
            assert lead % p
            inv = pow(lead, -1, p)
            coeffs = [(int(c[i]) * inv) % p for i in range(len(c))]
            return list(reversed(coeffs))
        vecs.append(nxt)


def maximal_ideals(S: ZOrder, p: int) -> list[MaxIdeal]:
    """All maximal ideals of ``S`` over ``p`` (Berlekamp splitting of ``S/p``)."""
    if p in S._maxideals:
        return S._maxideals[p]
    P = _P()
    d = S.d
    F = _frobenius_matrix(S, p)
    fixed = _kernel_mod_p((F - np.identity(d, dtype=object)) % p, p, d)
    idems = [np.array(S.one, dtype=object) % p]
    for z in fixed:
        new = []
        for e in idems:
            mp = _minpoly_mod_p(S, z, e, p)          # splits into distinct linear factors
            roots = [c for c in range(p) if sum(a * pow(c, len(mp) - 1 - i, p) for i, a in enumerate(mp)) % p == 0]
            if len(roots) <= 1:
                new.append(e)
                continue
            ze = S.mul_mod(z, e, p)
            for c in roots:
                ec = e.copy()
                for c2 in roots:
                    if c2 != c:
                        fac = (ze - c2 * e) * pow(c - c2, -1, p) % p
                        ec = S.mul_mod(ec, fac, p)
                new.append(ec % p)
        idems = new
    assert len(idems) == len(fixed), "Berlekamp: idempotent count mismatch"
    rad = _radical_mod_p(S, p)
    out = []
    for e in idems:
        eS = _colspace_mod_p([S.mul_mod(e, S.basis_vec(i), p) for i in range(d)], p, d)
        erad = _colspace_mod_p([S.mul_mod(e, r, p) for r in rad], p, d)
        m = MaxIdeal(S, p, [int(x) for x in e], local_rank=len(eS), residue_degree=len(eS) - len(erad))
        for g, x in S.gens.items():
            mp = _minpoly_mod_p(S, x, e, p)
            fac = P.factor(P.Pol(mp) * P.Mod(1, p))
            irr = fac[0, 0]
            assert fac.nrows() == 1
            m.labels[g] = [int(P.lift(c)) for c in reversed(list(P.Vecrev(irr)))]
            if len(m.labels[g]) == 2:
                m.values[g] = (-m.labels[g][1]) % p
        out.append(m)
    out.sort(key=lambda m: [tuple(m.labels[g]) for g in sorted(m.labels)])
    S._maxideals[p] = out
    return out


def find_maximal_ideal(S: ZOrder, p: int, eig: dict[str, "int | Sequence[int]"]) -> MaxIdeal:
    """The unique maximal ideal over ``p`` with the given residues (``int``) or irreducible polynomials (list)."""
    hits = []
    for m in maximal_ideals(S, p):
        ok = True
        for g, v in eig.items():
            if isinstance(v, int):
                ok &= m.values.get(g) == v % p
            else:
                ok &= m.labels.get(g) == [int(c) % p for c in v]
        if ok:
            hits.append(m)
    if len(hits) != 1:
        raise ValueError(f"{len(hits)} maximal ideals match {eig}")
    return hits[0]


def push_max_ideal(m: MaxIdeal, phi: ZHom) -> MaxIdeal | None:
    """The maximal ideal of ``phi.tgt`` over ``m`` when ``phi(e_m)`` is primitive; ``None`` if ``phi(e_m) = 0``
    (the component vanishes); raises if several maximal ideals lie over ``m``."""
    O = phi.tgt
    assert isinstance(O, ZOrder)
    if O.d == 0:
        return None
    e = [int(x) % m.p for x in phi(m.ebar)]
    if not any(e):
        return None
    for v in maximal_ideals(O, m.p):
        if [x % m.p for x in v.ebar] == e:
            return v
    raise ValueError("several maximal ideals of the target lie over m")


# ------------------------------------------------------------------------------------------------ local invariants

def local_length(X: ZIdeal, Y: ZIdeal, m: MaxIdeal) -> int | float:
    """``length_{Z_p} (X/Y) (x)_S S_m`` for ideals ``Y <= X`` of ``S`` (``inf`` if not finite).

    Exact: the precision ``M`` exceeds the ``p``-part of the global elementary divisors of ``Y`` in ``X``.
    """
    S, p = X.order, m.p
    assert Y.order is S and m.order is S
    if X.rank == 0:
        return 0
    divs, _free = Y.divisors_in(X)
    t = sum(vp(x, p) for x in divs)
    M = t + 2
    q = p ** M
    e = m.idempotent(M)
    r = X.rank
    # action of e on X in X-coordinates mod q, from the exact action of the basis e_k on X (X need not be saturated)
    E = np.zeros((r, r), dtype=object)
    for k in range(S.d):
        if e[k] % q == 0:
            continue
        Ak = _coords(X.basis, [S.mul(S.basis_vec(k), b) for b in X.basis], S.d)
        E = (E + int(e[k]) * np.array(Ak, dtype=object).T) % q
    C = np.array(_coords(X.basis, Y.basis, S.d), dtype=object).T if Y.rank else np.zeros((r, 0), dtype=object)
    # basis of the free Z/q-module e X/q: columns of E independent mod p
    Ecols = [E[:, j] for j in range(r)]
    sel, cur = [], []
    for j, c in enumerate(Ecols):
        if _rank_mod_p(cur + [c], p) > len(cur):
            cur.append(c)
            sel.append(j)
    rm = len(sel)
    if rm == 0:
        return 0
    F = np.array([list(Ecols[j]) for j in sel], dtype=object).T          # r x rm
    # left inverse mod q: rows where F is invertible mod p
    rows, curr = [], []
    for i in range(r):
        if _rank_mod_p(curr + [F[i, :]], p) > len(curr):
            curr.append(F[i, :])
            rows.append(i)
    P = _P()
    Fsub = pmat([[int(F[i, j]) for j in range(rm)] for i in rows])
    Finv = P.matinvmod(Fsub, q) if hasattr(P, "matinvmod") else (Fsub * P.Mod(1, q)) ** -1
    Finv = np.array([[int(P.lift(Finv[i, j])) for j in range(rm)] for i in range(rm)], dtype=object)
    EC = E.dot(C) % q if C.shape[1] else np.zeros((r, 0), dtype=object)
    G = Finv.dot(EC[rows, :]) % q if C.shape[1] else np.zeros((rm, 0), dtype=object)
    Gq = [[int(G[i, j]) for j in range(G.shape[1])] + [q * int(i == j2) for j2 in range(rm)] for i in range(rm)]
    dv = smith_divisors(Gq, rm, G.shape[1] + rm)
    assert len(dv) == rm
    out = 0
    for x in dv:
        v = vp(x, p)
        if v >= M:
            return float("inf")
        out += v
    return out


def gorenstein_test(m: MaxIdeal, seed: int = 0, tries: int = 60) -> dict:
    """Is ``S_m`` ``Z_p``-Gorenstein, i.e. ``Hom_{Z_p}(S_m, Z_p)`` cyclic over ``S_m``?

    Criterion (Nakayama, ``lem:s06-G`` with ``p = (p)``): ``dim_{F_p} soc(S_m/p) = f`` (residue degree).  A witness
    ``l`` in ``Hom(S_m/p, F_p)`` with nondegenerate ``(x, y) -> l(xy)`` is searched independently (seeded).
    """
    S, p = m.order, m.p
    d = S.d
    e = np.array(m.ebar, dtype=object) % p
    A = _colspace_mod_p([S.mul_mod(e, S.basis_vec(i), p) for i in range(d)], p, d)       # e S/p
    rad = _colspace_mod_p([S.mul_mod(e, r, p) for r in _radical_mod_p(S, p)], p, d)
    f = len(A) - len(rad)
    # socle: x = sum a_i A_i with x r = 0 for r in rad
    if rad:
        Amat = np.array([list(a) for a in A], dtype=object).T                            # d x rk
        cons = np.vstack([S.lmat_mod(r, p).dot(Amat) % p for r in rad])
        soc = len(_kernel_mod_p(cons, p, len(A)))
    else:
        soc = len(A)
    gor = soc == f
    rng = random.Random(seed)
    witness = None
    prods = [[S.mul_mod(a, b, p) for b in A] for a in A]
    for _ in range(tries if gor else 0):
        lvec = np.array([rng.randrange(p) for _ in range(d)], dtype=object)
        G = pmat([[int(lvec.dot(prods[i][j]) % p) for j in range(len(A))] for i in range(len(A))])
        if int(_P().matdet(G)) % p:
            witness = [int(x) for x in lvec]
            break
    return {"gorenstein": gor, "socle_dim": soc, "residue_degree": f, "local_rank": len(A),
            "trace_witness_found": witness is not None}
