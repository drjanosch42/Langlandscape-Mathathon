@dataclass
class Character:
    """A ring map ``mu = phi: S -> O`` (``phi`` a :class:`ZHom` with ``phi.src = S``, ``phi.tgt = O``)."""

    phi: ZHom

    @property
    def S(self) -> ZOrder:
        return self.phi.src

    @property
    def O(self) -> ZOrder:
        return self.phi.tgt

    @classmethod
    def from_rep(cls, T: HeckeAlgebra, rho: str) -> "Character":
        """``O = T / ker(T -> End V_rho)`` with the quotient map (``V_rho`` should be one Galois orbit)."""
        O, q = T.quotient(T.kernel_of_rep(rho), name=f"O_{rho}")
        return cls(q)

    @classmethod
    def from_values(cls, T: HeckeAlgebra, O: ZOrder, values: dict[str, Sequence[int]]) -> "Character":
        return cls(T.hom_from_values(O, values))

    @classmethod
    def rational(cls, T: HeckeAlgebra, values: dict[str, int]) -> "Character":
        return cls(T.hom_from_values(ZOrder.integers(), {g: [int(v)] for g, v in values.items()}))

    def kernel(self) -> ZIdeal:
        return self.phi.kernel()

    def place(self, m: MaxIdeal) -> MaxIdeal:
        v = push_max_ideal(m, self.phi)
        if v is None:
            raise ValueError("mu does not factor through S_m (mu(e_m) = 0)")
        return v

    def through_quotient(self, q: ZHom) -> "Character":
        """The induced ``mu': S/I -> O`` for a quotient map ``q: S -> S/I`` with ``mu(I) = 0`` (checked)."""
        I = q.kernel()
        assert all(not any(self.phi(b)) for b in I.basis), "mu does not vanish on the kernel"
        phi2 = ZHom(q.tgt, self.O, self.phi.A * q.section)
        phi2.check_ring_hom()
        return Character(phi2)


def _kron(A, B):
    P = get_pari()
    return P("(A,B)->my(a=matsize(A),b=matsize(B));matrix(a[1]*b[1],a[2]*b[2],i,j,"
             "A[(i-1)\\b[1]+1,(j-1)\\b[2]+1]*B[(i-1)%b[1]+1,(j-1)%b[2]+1])")(A, B)


def eta(chi: Character, base_change: bool = True, seed: int = 1) -> ZIdeal:
    """The congruence ideal ``eta(S (x) O, mu (x) O) = mu_O(Ann ker mu_O)`` as an ideal of ``O`` (``def:s06-rings``).

    ``ker mu_O`` is generated by ``g (x) 1 - 1 (x) mu(g)`` for ring generators ``g`` of ``S``.  The annihilator is
    cut out over ``Q`` (a random combination first, then every generator until all are killed) and saturated.
    ``base_change=False`` returns ``mu(Ann_S ker mu) O`` instead.
    """
    P = get_pari()
    S, O, phi = chi.S, chi.O, chi.phi
    if not base_change:
        return O.ideal([phi(x) for x in chi.kernel().ann().basis])
    d, r = S.d, O.d
    Id, Ir = P.matid(d), P.matid(r)
    gens = list(S.gens.values()) + [S.basis_vec(i) for i in range(d)]

    def lmat(x):
        return _kron(S.lmat(x), Ir) - _kron(Id, O.lmat(phi(x)))

    rng = random.Random(seed)
    combo = [0] * d
    for g in S.gens.values():
        combo = S.add(combo, S.scale(rng.randrange(1, 1000), g))
    K = None
    for x in [combo] + gens:
        M = lmat(x) if K is None else lmat(x) * K
        if K is not None and M == P.matrix(M.nrows(), M.ncols()):
            continue
        ker = P.matker(M)
        K = ker if K is None else K * ker
        if K.ncols() == 0:
            return ZIdeal(O, [])
    ann = P.matrixqz(K, -2)
    muO = P.matconcat([O.lmat(phi(S.basis_vec(i))) for i in range(d)])        # r x (d r): e_i (x) c_a -> mu(e_i) c_a
    return O.ideal(mat_cols(muO * ann))


def image_ideal(chi: Character, I: ZIdeal) -> ZIdeal:
    """``mu(I) O`` (e.g. ``c_q = lambda(b)``, ``def:s06-ctam``)."""
    return chi.phi.image(I, as_ideal=True)


def place_info(v: MaxIdeal) -> dict:
    """Residue degree ``f``, ramification index ``e = rank O_v / f``, and whether ``O_v`` is a DVR
    (``dim_{F_p} m_v/m_v^2 = f``)."""
    O = v.order
    mv = v.ideal()
    l1 = local_length(O.whole(), mv, v)
    l2 = local_length(O.whole(), mv * mv, v)
    f = v.residue_degree
    assert l1 == f
    return {"residue_degree": f, "local_rank": v.local_rank, "ramification_index": Fraction(v.local_rank, f),
            "dvr": (l2 - l1) == f}


def ord_at(I: ZIdeal, v: MaxIdeal) -> Fraction | float:
    """``length_{Z_p}(O_v / I_v) / f_v``: ``ord_varpi(I)`` when ``O_v`` is a DVR."""
    L = local_length(I.order.whole(), I, v)
    if L == float("inf"):
        return L
    return Fraction(L, v.residue_degree)


def _num(x):
    if isinstance(x, Fraction):
        return int(x) if x.denominator == 1 else f"{x.numerator}/{x.denominator}"
    return x if x != float("inf") else "inf"


def defect(T: HeckeAlgebra, chi: Character, m: MaxIdeal, new: str = "new", old: str = "old",
           naive: bool = True) -> dict:
    """All stage-6 invariants at ``(m, mu)``; ``mu`` must factor through the ``new`` quotient.

    Returns ``ord`` of ``eta = eta(S, lam)``, ``c = lam(b)``, ``eta_new = eta(S', lam')`` at the place of ``O`` over
    ``m``; Gorenstein tests of ``S_m``, ``S'_m``; Lemma D (a) checks; the congruence-module length
    ``length S'_m / c = length S_m/(a+b)``; and ``thm_E_identity``: ``ord eta == ord c + ord eta_new``.  This identity
    is *proved* (Thm E(iii)) when ``S_m`` is Gorenstein and ``O_v`` is a DVR.
    """
    a, b = T.kernel_of_rep(new), T.kernel_of_rep(old)
    Sn, qn = T.quotient(a, name="T'")
    chi_n = chi.through_quotient(qn)
    v = chi.place(m)
    mn = push_max_ideal(m, qn)
    Sold, qo = T.quotient(b, name="T''")
    mo = push_max_ideal(m, qo)
    e_ = ord_at(eta(chi), v)
    c_ = ord_at(image_ideal(chi, b), v)
    en = ord_at(eta(chi_n), v)
    cS = qn.image(b, as_ideal=False)
    out = {
        "m": m.describe(),
        "ranks": {"S_m": m.local_rank, "S_new_m": mn.local_rank if mn else 0, "S_old_m": mo.local_rank if mo else 0,
                  "O": chi.O.d},
        "place": {k: _num(x) for k, x in place_info(v).items()},
        "lemma_D": {"a_cap_b_zero": a.intersect(b).rank == 0, "ranks_add": a.rank + b.rank == T.d,
                    "ann_a_eq_b": a.ann() == b, "ann_b_eq_a": b.ann() == a},
        "gorenstein": {"S_m": gorenstein_test(m), "S_new_m": gorenstein_test(mn) if mn else None,
                       "S_old_m": gorenstein_test(mo) if mo else None},
        "ord": {"eta": _num(e_), "c": _num(c_), "eta_new": _num(en)},
        "congruence_module_length": local_length(Sn.whole(), cS, mn) if mn else 0,
        "check_length_S_mod_a_plus_b": local_length(T.whole(), a + b, m),
    }
    if naive:
        out["ord"]["eta_no_base_change"] = _num(ord_at(eta(chi, base_change=False), v))
    out["thm_E_identity"] = e_ == c_ + en
    return out


# ------------------------------------------------------------------------------------------------ toys

def toy_l10a(p: int, t: int) -> tuple[HeckeAlgebra, Character, MaxIdeal]:
    """``S = {(x, y) in Z_p^2 : x = y mod p^t}`` = ``Z[T]``, ``T = diag(p^t, 0)``; new = first, old = second
    coordinate, ``lam = (x, y) -> x``.  Prediction (``ss:s06-ca``): ``eta = c = p^t``, ``eta_new = 1``."""
    T = HeckeAlgebra({"T": [[p ** t, 0], [0, 0]]}, {"new": {"T": [[p ** t]]}, "old": {"T": [[0]]}}, name="S_toy")
    chi = Character.from_rep(T, "new")
    return T, chi, find_maximal_ideal(T, p, {"T": 0})


def toy_non_gorenstein(p: int) -> tuple[HeckeAlgebra, Character, MaxIdeal]:
    """``S = {(x, y, z) : x = y = z mod p}`` (``S/p = F_p[u, w]/(u, w)^2``, socle of dim 2: not Gorenstein); new =
    coordinates 1, 3, old = coordinate 2, ``lam`` = first coordinate.  Here ``eta = (p)`` but
    ``c * eta_new = (p^2)``: Thm E fails without (Gor_S)."""
    T = HeckeAlgebra({"T1": [[p, 0, 0], [0, 0, 0], [0, 0, 0]], "T2": [[0, 0, 0], [0, p, 0], [0, 0, 0]]},
                     {"new": {"T1": [[p, 0], [0, 0]], "T2": [[0, 0], [0, 0]]},
                      "old": {"T1": [[0]], "T2": [[p]]},
                      "f": {"T1": [[p]], "T2": [[0]]}}, name="S_nonGor")
    chi = Character.from_rep(T, "f")
    return T, chi, find_maximal_ideal(T, p, {"T1": 0, "T2": 0})


def toy_ramified(p: int) -> tuple[HeckeAlgebra, Character, MaxIdeal]:
    """``S = Z[T]/(T(T^2 - p))``; new: ``T -> sqrt p`` (``O = Z[sqrt p]``, ramified), old: ``T -> 0``.  Monogenic, so
    Gorenstein; ``eta = (F'(sqrt p)) = (2p)``: ``ord_varpi = 2 = 1 (c) + 1 (eta_new)``; no base change gives 1."""
    T = HeckeAlgebra({"T": [[0, p, 0], [1, 0, 0], [0, 0, 0]]},
                     {"new": {"T": [[0, p], [1, 0]]}, "old": {"T": [[0]]}}, name="S_ram")
    chi = Character.from_rep(T, "new")
    return T, chi, find_maximal_ideal(T, p, {"T": 0})


def example_level3_weight12() -> tuple[HeckeAlgebra, Character, MaxIdeal]:
    """``S_12(Gamma_0(3))``, ``p = 17``: the 3-new form congruent to ``Delta`` (``T2 = 10``, ``U3 = -5`` mod 17)."""
    D = ha.mf_qnew_qold(3, 12, 3)
    T = HeckeAlgebra(D["full"], {"new": D["new"], "old": D["old"]}, name="T_12(3)")
    chi = Character.from_rep(T, "new")
    return T, chi, find_maximal_ideal(T, 17, {"T2": 10, "T3": 12})


