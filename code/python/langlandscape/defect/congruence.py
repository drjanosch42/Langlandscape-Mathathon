"""S06-C1: congruence ideals ``eta(S, mu)``, ``c = lambda(b)``, Gorenstein tests, the Thm-E identity.

Tex: ``plan/staged/stage-06-integral-defect.tex``: ``def:s06-rings`` (``a``, ``b``, ``eta(S, mu) := mu(Ann_S ker mu)``),
``def:s06-ctam`` (``c = im(b -> S')``, ``c_q = lambda(b)``), ``lem:s06-S`` (base change), ``lem:s06-G`` (Gorenstein from
one fibre), ``lem:s06-D``, ``thm:s06-E`` (``eta(S, lam) = c_q * eta(S', lam')`` under (Gor_S), over a DVR), toy in
``ss:s06-ca``.  Status of every number produced here: *computed*.

API (for C2 C4(i) regression, C3 T4 Hecke side, C4 T5 GL2 side, C7 H3 validation)
==================================================================================
Building the algebra (:mod:`.hecke_alg`)::

    D = mf_qnew_qold(N, k, q)                     # integral Hecke matrices: D["full"], D["new"], D["old"] (T_n, U_n for n|N)
    T = HeckeAlgebra(D["full"], {"new": D["new"], "old": D["old"]})   # Z-order generated by the matrices (exact HNF)
    T = HeckeAlgebra({"T": [[25, 0], [0, 0]]}, {"new": {"T": [[25]]}, "old": {"T": [[0]]}})        # any integer matrices
    a, b = T.kernel_of_rep("new"), T.kernel_of_rep("old")             # a = ker(T -> T'), b = ker(T -> T'') (saturated)
    x = T.gen("T3"); y = T.add(T.mul(x, x), T.scalar(-7)); T.poly([1, 0, -7], x)   # element arithmetic (coords)
    I = T.ideal([y]);  I + J;  I * J;  I.intersect(J);  I.ann();  I <= J;  I.index_in(J)   # exact over Z

Maximal ideals over ``p`` and localisation::

    ms = T.maximal_ideals(p)                      # list of MaxIdeal: .local_rank, .residue_degree, .labels, .values
    m  = find_maximal_ideal(T, p, {"T2": 10, "T3": 12})     # by residues (int) or irreducible polys mod p (list)
    local_length(T.whole(), T.ideal([delta]), m)            # length_{Z_p} T_m/(delta)   (C3)
    gorenstein_test(m)                            # {"gorenstein", "socle_dim", "residue_degree", "local_rank", ...}
    m.idempotent(M)                               # e_m mod p^M;  m.ideal() = m as a global ideal

Characters ``mu: S -> O`` (``O`` a Z-order, e.g. ``Z`` or the Hecke order of an eigenform orbit)::

    chi = Character.from_rep(T, "f")              # O = T/ker(T -> End V_f), mu = quotient map (V_f = an orbit space)
    chi = Character.from_rep(T, "new")            # when the q-new space is a single rational eigenform
    chi = Character.from_values(T, O, {"T2": [..], ...})     # O any ZOrder (e.g. ZOrder.from_polynomial), checked
    chi = Character.rational(T, {"T2": -24, "T3": 252})      # O = Z
    v = chi.place(m)                              # the maximal ideal of O over m
    eta(chi)                                      # eta(S (x) O, mu (x) O) as an ideal of O   (lem:s06-S base change)
    eta(chi, base_change=False)                   # mu(Ann_S ker mu) O  (no base change; differs if O != Z)
    image_ideal(chi, b)                           # c_q = mu(b) O
    ord_at(I, v)                                  # ord_varpi of an O-ideal at v (Fraction if O_v is not a DVR)
    place_info(v)                                 # {"residue_degree", "ramification_index", "dvr"}

The whole stage-6 package at one ``(m, mu)``::

    res = defect(T, chi, m, new="new", old="old") # dict: ords of eta, c, eta_new (+ naive), Gorenstein of S_m, S'_m,
                                                  # Lemma D checks, congruence-module length, "thm_E_identity" bool

Conventions.  Rings are commutative ``Z``-orders; the ``p``-adic objects are their completions ``S (x) Z_p = prod S_m``;
``eta`` and ``c`` are computed globally and exactly over ``Z`` and then measured at the place ``v`` of ``O`` over
``m``.  This is legitimate because annihilators and kernels are saturated (they commute with ``(x) Z_p``) and
``mu(e_{m'}) = 0`` for ``m' != m``.  ``eta`` uses the base change ``S (x)_Z O -> O``.  This is the congruence ideal of
an ``O``-valued eigensystem (Kim-Ota / Hsieh), which also counts congruences with Galois conjugates.  The Gorenstein
test is over ``Z_p``.  By ``lem:s06-S`` it is equivalent to the test over ``O_v``.  Lengths are exact (see
:func:`.hecke_alg.local_length`).
"""

