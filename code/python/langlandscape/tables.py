"""S01-T2: backup slide with the Eichler mass formula and the class-set table.

The slide is generated from committed results only:
``code/results/s01/classsets.json`` (h(D), |Gamma_x|, mass) and
``code/results/s01/brandt_w2.json`` (charpoly of T_2, or of T_ell for D = 2).
Nothing is recomputed here; the two files are only cross-checked.

Run as ``python -m langlandscape.tables`` to write ``talk/slides/s01-mass-table.tex``.
"""

from __future__ import annotations

from fractions import Fraction

from langlandscape import results

CLASSSETS = "s01/classsets.json"
BRANDT = "s01/brandt_w2.json"
SLIDE_RELPATH = "talk/slides/s01-mass-table.tex"
HEADER = (
    "% GENERATED by code/python/langlandscape/tables.py from "
    "code/results/s01/{classsets,brandt_w2}.json — do not edit"
)
FORMULA = r"\[\sum_{x}\frac{1}{|\Gamma_x|}=\frac{1}{24}\prod_{\ell\mid D}(\ell-1)\]"
SOURCES = (
    r"{\tiny Sources: code/results/s01/classsets.json; code/results/s01/brandt\_w2.json. "
    r"$D=2$: $T_3$ (recorded $\ell=3$).}"
)


def _primes_upto(n: int) -> list[int]:
    return [p for p in range(2, n + 1) if all(p % q for q in range(2, int(p ** 0.5) + 1))]


PRIMES = _primes_upto(53)


def _poly(coeffs: list[int]) -> str:
    """Render a monic polynomial given by low-to-high coefficients, e.g. [-6,-1,1] -> x^2-x-6."""
    if not coeffs or coeffs[-1] != 1:
        raise ValueError(f"charpoly is not monic: {coeffs}")
    out = ""
    for i in range(len(coeffs) - 1, -1, -1):
        c = coeffs[i]
        if c == 0:
            continue
        mag = abs(c)
        if i == 0:
            body = str(mag)
        else:
            var = "x" if i == 1 else f"x^{i}"
            body = var if mag == 1 else f"{mag}{var}"
        if out == "":
            out = ("-" if c < 0 else "") + body
        else:
            out += ("-" if c < 0 else "+") + body
    return out


def _rows() -> list[dict]:
    classsets = results.read(CLASSSETS)["data"]
    brandt = results.read(BRANDT)["data"]["T2_table"]
    rows = []
    for D in PRIMES:
        key = str(D)
        c = classsets[key]
        t = brandt[key]
        if c["h"] != t["h"] or sorted(c["gammas"]) != sorted(t["gammas_multiset"]):
            raise ValueError(f"classsets.json and brandt_w2.json disagree at D={D}")
        if D != 2 and t["ell"] != 2:
            raise ValueError(f"expected T_2 for D={D}, found T_{t['ell']}")
        mass = Fraction(c["mass"])
        rows.append({
            "D": D,
            "h": c["h"],
            "gammas": sorted(c["gammas"]),
            "mass": f"{mass.numerator}/{mass.denominator}" if mass.denominator != 1 else str(mass.numerator),
            "charpoly": _poly(t["charpoly"]),
            "ell": t["ell"],
        })
    return rows


def _tabular(rows: list[dict]) -> str:
    lines = [
        r"\begin{tabular}{rrlrl}",
        r"\toprule",
        r"$D$ & $h(D)$ & $\{|\Gamma_x|\}$ & mass & $\chi_{T_2}(x)$ \\",
        r"\midrule",
    ]
    for r in rows:
        gam = r"\{" + ",".join(str(g) for g in r["gammas"]) + r"\}"
        char = f"${r['charpoly']}$"
        if r["ell"] != 2:
            char += f" ($T_{r['ell']}$)"
        lines.append(f"{r['D']} & {r['h']} & ${gam}$ & ${r['mass']}$ & {char} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines)


def render_mass_table() -> str:
    """Return the full text of ``talk/slides/s01-mass-table.tex``."""
    body = "\n".join([
        HEADER,
        r"\begin{frame}{Backup: Eichler mass formula and class sets ($D$ prime, $D\le 53$)}",
        "  " + FORMULA,
        r"  {\centering\scriptsize\setlength{\tabcolsep}{4pt}\renewcommand{\arraystretch}{0.8}",
        _tabular(_rows()),
        r"  \par}",
        "  " + SOURCES,
        r"\end{frame}",
    ])
    return body + "\n"


def main() -> None:
    path = results.repo_root() / SLIDE_RELPATH
    path.write_text(render_mass_table(), encoding="utf-8")
    print(path)


if __name__ == "__main__":
    main()
