"""S02-C4: torsion example D=2 (Hurwitz order), q=3, U = O^_^x  (tex H02.2(d), rem:s02-torsion).

Direct quaternion arithmetic in Hamilton coordinates (1,i,j,k), B = (-1,-1 / Q).
Tree of PGL_2(Q_3): vertex v0 = standard (stabiliser in Gamma_U = O[1/3]^1 is O^x),
vertex v1 = pi.v0 for pi in O of reduced norm 3, with Gamma_{v1} = pi O^x pi^{-1}
(= elements of norm 1 lying in pi O_3 pi^{-1} at 3 and in O_l at l != 3).
Gamma_e = Gamma_{v0} cap Gamma_{v1}.  The S01 ``DefiniteAlgebra(2)`` is used to confirm
a = b = -1, h = 1 and |O^x| = 24 (the Hurwitz order is the unique maximal order up to conjugacy).
Conventions: |Gamma_x| counts -1; the edge mass is sum 1/|Gamma_e| (Gamma_e, not Gamma_e/+-1).
"""

from __future__ import annotations

import itertools
from fractions import Fraction as F

from . import results
from .quat import DefiniteAlgebra

H = F(1, 2)


def qmul(x, y):
    a1, b1, c1, d1 = x
    a2, b2, c2, d2 = y
    return (a1*a2 - b1*b2 - c1*c2 - d1*d2, a1*b2 + b1*a2 + c1*d2 - d1*c2,
            a1*c2 - b1*d2 + c1*a2 + d1*b2, a1*d2 + b1*c2 - c1*b2 + d1*a2)


def qconj(x):
    return (x[0], -x[1], -x[2], -x[3])


def qnrd(x):
    return sum(c * c for c in x)


def qinv(x):
    n = qnrd(x)
    return tuple(c / n for c in qconj(x))


def in_hurwitz(x):
    return (all(c.denominator == 1 for c in x)
            or all((c - H).denominator == 1 for c in x))


def hurwitz_units():
    out = []
    for x in itertools.product([F(c) for c in (-1, 0, 1)], repeat=4):
        if qnrd(x) == 1:
            out.append(x)
    for s in itertools.product([-H, H], repeat=4):
        out.append(tuple(s))
    assert len(out) == 24
    return out


def elt_order(x):
    one = (F(1), F(0), F(0), F(0))
    y, n = x, 1
    while y != one:
        y, n = qmul(y, x), n + 1
    return n


def order_profile(G):
    prof = {}
    for g in G:
        n = elt_order(g)
        prof[n] = prof.get(n, 0) + 1
    return dict(sorted(prof.items()))


def derived_subgroup(G):
    Gs = set(G)
    comm = {qmul(qmul(a, b), qmul(qinv(a), qinv(b))) for a in G for b in G}
    S = set(comm)
    while True:  # closure under multiplication
        new = {qmul(a, b) for a in S for b in comm} | S
        if new == S:
            break
        S = new
    assert S <= Gs
    return S


def ab_cyclic(G, gens=None):
    """Abelianisation G/[G,G] as a cyclic group: returns (n, phi: G -> Z/n), n=|G^ab|.

    Asserts cyclicity (an element of G whose class has order n exists)."""
    C = derived_subgroup(G)
    n = len(G) // len(C)
    cosets = []  # representatives
    cls = {}
    for g in G:
        if g in cls:
            continue
        idx = len(cosets)
        cosets.append(g)
        for c in C:
            cls[qmul(g, c)] = idx
    assert len(cosets) == n
    one = (F(1), F(0), F(0), F(0))
    for t in G:  # find generator of G^ab
        k, y = 1, t
        while cls[y] != cls[one]:
            y, k = qmul(y, t), k + 1
        if k == n:
            break
    else:
        raise AssertionError("G^ab not cyclic")
    dlog = {}
    y = one
    for k in range(n):
        dlog[cls[y]] = k
        y = qmul(y, t)
    return n, {g: dlog[cls[g]] for g in G}, t


def compute() -> dict:
    # --- cross-check with S01 quat.py / classset ---
    B = DefiniteAlgebra(2)
    assert (B.a, B.b) == (-1, -1)
    cs = B.class_set()
    assert len(cs) == 1 and cs[0]["gamma"] == 24
    U = hurwitz_units()
    G0 = set(U)
    pi = (F(1), F(1), F(1), F(0))  # norm 3, in O
    assert qnrd(pi) == 3 and in_hurwitz(pi)
    pii = qinv(pi)
    G1 = {qmul(qmul(pi, u), pii) for u in U}
    # each element of G1 is a unit of O[1/3] of norm 1, integral away from 3
    for g in G1:
        assert qnrd(g) == 1
        assert all(c.denominator in (1, 2, 3, 6) for c in g)
    Ge = sorted(G0 & G1)
    # Gamma_{v1} acts on v1; check Gamma_e = stabiliser in G0 of the edge (v0,v1):
    # edges at v0 <-> O^x-orbit of pi O (4 left ideals O*K of norm 3 / cosets): orbit count
    # u.pi O ... transitivity: |G0|/|Ge| = number of edges at v0 in G0-orbit of this edge
    orbit_size = len(G0) // len(Ge)
    q = 3
    n0, phi0, t0 = ab_cyclic(sorted(G0))
    n1, phi1, t1 = ab_cyclic(sorted(G1))
    # Gamma_e cyclic?
    Ge_prof = order_profile(Ge)
    gen_e = next(g for g in Ge if elt_order(g) == len(Ge))
    # H_1 = (Z/n0 + Z/n1) / <(phi0(g), -phi1(g)) : g in Ge>
    img = set()
    for g in Ge:
        img.add((phi0[g] % n0, (-phi1[g]) % n1))
    # subgroup generated by images (Ge cyclic => by image of gen_e)
    sub = {((k * phi0[gen_e]) % n0, (-k * phi1[gen_e]) % n1) for k in range(len(Ge))}
    assert img <= sub
    coker_order = n0 * n1 // len(sub)
    # structure of coker: exponent of the quotient
    quo_exp = 1
    from math import lcm
    for a in range(n0):
        for b in range(n1):
            k = 1
            while ((k * a) % n0, (k * b) % n1) not in sub:
                k += 1
            quo_exp = lcm(quo_exp, k)
    coker_cyclic = quo_exp == coker_order
    # H_1(Gamma_U) = coker (Mayer-Vietoris, Gamma_e -> Gamma_v0 + Gamma_v1 injective on H_0)
    return {
        "D": 2, "q": q, "level": "U = O^_^x (Hurwitz order)", "pi": [str(c) for c in pi],
        "class_number_S01": len(cs), "gamma_S01": [c["gamma"] for c in cs],
        "vertex_orbits_per_type": 1,
        "gamma_v0_order": len(G0), "gamma_v1_order": len(G1),
        "gamma_v0_element_orders": order_profile(sorted(G0)),
        "gamma_v1_element_orders": order_profile(sorted(G1)),
        "gamma_v_is_SL2F3": (len(G0) == 24 and order_profile(sorted(G0)) ==
                             {1: 1, 2: 1, 3: 8, 4: 6, 6: 8} and n0 == 3),
        "gamma_v_abelianisation_order": [n0, n1],
        "gamma_e_order": len(Ge), "gamma_e_element_orders": Ge_prof,
        "gamma_e_cyclic": Ge_prof.get(len(Ge)) is not None and Ge_prof[len(Ge)] > 0,
        "gamma_e": [[str(c) for c in g] for g in Ge],
        "edges_at_v0_in_orbit_of_e": orbit_size, "edges_at_v0": q + 1,
        "one_edge_orbit": orbit_size == q + 1,
        "mass_vertex": str(F(1, 24)), "mass_edge_Ge": str(F(1, len(Ge))),
        "mass_edge_formula_(q+1)/24": str(F(q + 1, 24)),
        "mass_edge_Ge_mod_pm1": str(F(1, len(Ge) // 2)),
        "mass_convention": "sum 1/|Gamma_e| with Gamma_e containing -1; modulo +-1 it is 1/3",
        "edge_to_vertex_images_in_ab": {
            "image_of_gen_e_in_Z/%d+Z/%d" % (n0, n1): [phi0[gen_e] % n0, (-phi1[gen_e]) % n1],
            "image_order": len(sub)},
        "H1_Gamma_U_Z_order": coker_order, "H1_Gamma_U_Z_cyclic": coker_cyclic,
        "H1_Gamma_U_Z_exponent": quo_exp,
        "H1_Gamma_U_Z_description": ("Z/%d" % coker_order) if coker_cyclic else "non-cyclic",
        "tex_expectation": "Gamma_e cyclic order 6, H_1 = Z/3",
        "matches_tex": (len(Ge) == 6 and coker_order == 3 and coker_cyclic),
    }


def main() -> None:
    with results.Timer() as t:
        data = compute()
    results.write(
        "s02/torsion.json", data, script="code/python/langlandscape/torsion_s02.py",
        params={"D": 2, "q": 3, "level": "O^_^x", "pi": "1+i+j"}, runtime_s=t.seconds,
        notes="S02-C4; computed, direct quaternion arithmetic; H_1 = coker via Mayer-Vietoris",
    )


if __name__ == "__main__":
    main()
