// Bareiss determinant of a 4x4 integer matrix (exact, checked)
i128 det4(i128 m[4][4]) {
    i128 a[4][4];
    for (int i = 0; i < 4; ++i)
        for (int j = 0; j < 4; ++j) a[i][j] = m[i][j];
    i128 prev = 1;
    int sign = 1;
    for (int k = 0; k < 3; ++k) {
        if (a[k][k] == 0) {
            int r = -1;
            for (int i = k + 1; i < 4; ++i)
                if (a[i][k] != 0) r = i;
            if (r < 0) return 0;
            for (int j = 0; j < 4; ++j) std::swap(a[k][j], a[r][j]);
            sign = -sign;
        }
        for (int i = k + 1; i < 4; ++i)
            for (int j = k + 1; j < 4; ++j)
                a[i][j] = exact_div(add_chk(mul_chk(a[i][j], a[k][k]), -mul_chk(a[i][k], a[k][j])), prev);
        prev = a[k][k];
    }
    return sign * a[3][3];
}

// lattice in the standard basis, rows h / den
struct StdLat {
    const QuatAlgebra& B;
    Lat L;
    // trd(x conj y) * den^2 numerators
    i128 trd_num(const Vec4& x, const Vec4& y) const {
        Vec4 yc = y;
        for (int t = 1; t < 4; ++t) yc[t] = -yc[t];
        return 2 * B.mul_std(x, yc)[0];
    }
    bool integral() const {
        i128 d2 = mul_chk(L.den, L.den);
        for (int s = 0; s < 4; ++s)
            for (int t = 0; t < 4; ++t)
                if (trd_num(L.h[s], L.h[t]) % d2) return false;
        for (int s = 0; s < 4; ++s)
            if (trd_num(L.h[s], L.h[s]) % (2 * d2)) return false;  // nrd integral
        return true;
    }
    i128 disc() const {  // |det trd Gram| (requires integral())
        i128 g[4][4], d2 = mul_chk(L.den, L.den);
        for (int s = 0; s < 4; ++s)
            for (int t = 0; t < 4; ++t) g[s][t] = exact_div(trd_num(L.h[s], L.h[t]), d2);
        i128 d = det4(g);
        return d < 0 ? -d : d;
    }
};

// ring generated by the lattice L (std coordinates) -- assumes 1 in L. Returns false if a non-integral element appears.
bool ring_closure(const QuatAlgebra& B, Lat& L) {
    for (int it = 0; it < 32; ++it) {
        std::vector<Vec4> gens;
        i128 d2 = mul_chk(L.den, L.den);
        for (auto r : L.h) {
            for (auto& v : r) v = mul_chk(v, L.den);
            gens.push_back(r);
        }
        for (int s = 0; s < 4; ++s)
            for (int t = 0; t < 4; ++t) gens.push_back(B.mul_std(L.h[s], L.h[t]));
        Lat M = hnf(gens, d2);
        StdLat S{B, M};
        if (!S.integral()) return false;
        if (M == L) return true;
        L = M;
    }
    return false;
}

