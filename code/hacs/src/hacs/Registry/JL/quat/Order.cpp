MaxOrder::MaxOrder(i64 D) : B_(D) { build(); }
MaxOrder::MaxOrder(i64 D, i64 a, i64 b) : B_(D, a, b) { build(); }

void MaxOrder::build() {
    const i128 D = B_.D();
    const i128 target = D * D;
    Lat S;
    for (int c = 0; c < 4; ++c) {
        S.h[c] = Vec4{{0, 0, 0, 0}};
        S.h[c][c] = 1;
    }
    for (int round = 0; round < 64; ++round) {
        StdLat SL{B_, S};
        i128 d = SL.disc();
        if (d == target) break;
        if (d % target) throw std::logic_error("hacs_jl::MaxOrder: discriminant not a multiple of D^2");
        i128 ratio = d / target;
        i64 p = prime_factors(to_i64(ratio)).front();
        // trd of the basis vectors (integers): trd(h_t / den) = 2 h_t[0] / den
        i128 tr[4];
        for (int t = 0; t < 4; ++t) tr[t] = exact_div(2 * S.h[t][0], S.den);
        bool found = false;
        auto try_c = [&](const i64 c[4]) -> bool {
            if (!c[0] && !c[1] && !c[2] && !c[3]) return false;
            Vec4 x{{0, 0, 0, 0}};
            for (int t = 0; t < 4; ++t)
                for (int m = 0; m < 4; ++m) x[m] = add_chk(x[m], mul_chk(c[t], S.h[t][m]));
            QElt q;
            q.c = x;
            q.den = mul_chk(S.den, p);
            auto tn = B_.trd(q);
            if (tn.second != 1) return false;
            auto nn = B_.nrd(q);
            if (nn.second != 1) return false;
            // closure of S + Z x
            std::vector<Vec4> gens;
            for (auto r : S.h) {
                for (auto& v : r) v = mul_chk(v, p);
                gens.push_back(r);
            }
            gens.push_back(x);
            Lat T = hnf(gens, q.den);
            if (!ring_closure(B_, T)) return false;
            StdLat TL{B_, T};
            if (TL.disc() >= d) return false;
            S = T;
            return true;
        };
        if (p == 2) {
            for (int m = 1; m < 16 && !found; ++m) {
                i64 c[4] = {m & 1, (m >> 1) & 1, (m >> 2) & 1, (m >> 3) & 1};
                found = try_c(c);
            }
        } else {
            i64 inv2 = (p + 1) / 2;
            for (i64 c1 = 0; c1 < p && !found; ++c1)
                for (i64 c2 = 0; c2 < p && !found; ++c2)
                    for (i64 c3 = 0; c3 < p && !found; ++c3) {
                        i128 s = mod128(c1 * tr[1] + c2 * tr[2] + c3 * tr[3], p);
                        // tr[0] = 2: c0 = -s / 2 mod p
                        i64 c0 = (i64)mod128(-s * inv2, p);
                        i64 c[4] = {c0, c1, c2, c3};
                        found = try_c(c);
                    }
        }
        if (!found) throw std::runtime_error("hacs_jl::MaxOrder: p-saturation failed");
    }
    {
        StdLat SL{B_, S};
        if (SL.disc() != target) throw std::runtime_error("hacs_jl::MaxOrder: did not reach discriminant D^2");
        if (S.h[0][0] != S.den || S.h[0][1] || S.h[0][2] || S.h[0][3])
            throw std::logic_error("hacs_jl::MaxOrder: e_0 != 1");
    }
    E_ = S.h;
    den_ = S.den;
    Lat Enum;
    Enum.h = E_;
    for (int s = 0; s < 4; ++s)
        for (int t = 0; t < 4; ++t) {
            Vec4 pr = B_.mul_std(E_[s], E_[t]);
            for (auto& v : pr) v = exact_div(v, den_);
            Vec4 y = coords_in(Enum, pr);
            for (int u = 0; u < 4; ++u) C_[s][t][u] = to_i64(y[u]);
        }
    for (int t = 0; t < 4; ++t) tr_[t] = exact_div(2 * E_[t][0], den_);
    StdLat SL{B_, S};
    i128 d2 = mul_chk(den_, den_);
    for (int s = 0; s < 4; ++s)
        for (int t = 0; t < 4; ++t) G_.g[s][t] = exact_div(SL.trd_num(E_[s], E_[t]), d2);
    long double w[4] = {1.0L, sqrtl(-(long double)B_.a()), sqrtl(-(long double)B_.b()),
                        sqrtl((long double)B_.a() * (long double)B_.b())};
    for (int s = 0; s < 4; ++s)
        for (int m = 0; m < 4; ++m) emb_.v[s][m] = (long double)E_[s][m] * w[m] / (long double)den_;
}

Vec4 MaxOrder::mul(const Vec4& x, const Vec4& y) const {
    Vec4 z{{0, 0, 0, 0}};
    for (int s = 0; s < 4; ++s) {
        if (!x[s]) continue;
        for (int t = 0; t < 4; ++t) {
            if (!y[t]) continue;
            i128 xy = mul_chk(x[s], y[t]);
            for (int u = 0; u < 4; ++u)
                if (C_[s][t][u]) z[u] = add_chk(z[u], mul_chk(xy, C_[s][t][u]));
        }
    }
    return z;
}

i128 MaxOrder::trd(const Vec4& x) const {
    i128 t = 0;
    for (int s = 0; s < 4; ++s) t = add_chk(t, mul_chk(x[s], tr_[s]));
    return t;
}

Vec4 MaxOrder::conj(const Vec4& x) const {
    Vec4 z{{-x[0], -x[1], -x[2], -x[3]}};
    z[0] = add_chk(z[0], trd(x));
    return z;
}

i128 MaxOrder::nrd(const Vec4& x) const { return exact_div(qform(G_, x), 2); }

i128 MaxOrder::disc() const {
    i128 g[4][4];
    for (int s = 0; s < 4; ++s)
        for (int t = 0; t < 4; ++t) g[s][t] = G_.g[s][t];
    i128 d = det4(g);
    return d < 0 ? -d : d;
}

QElt MaxOrder::to_std(const Vec4& x, i128 den) const {
    QElt q;
    for (int s = 0; s < 4; ++s)
        for (int m = 0; m < 4; ++m) q.c[m] = add_chk(q.c[m], mul_chk(x[s], E_[s][m]));
    q.den = mul_chk(den, den_);
    q.normalise();
    return q;
}

Lat MaxOrder::unit() const {
    Lat L;
    for (int c = 0; c < 4; ++c) {
        L.h[c] = Vec4{{0, 0, 0, 0}};
        L.h[c][c] = 1;
    }
    return L;
}

Lat MaxOrder::product(const Lat& A, const Lat& Bl, i128 index) const {
    std::vector<Vec4> gens;
    gens.reserve(16);
    for (int s = 0; s < 4; ++s)
        for (int t = 0; t < 4; ++t) gens.push_back(mul(A.h[s], Bl.h[t]));
    i128 den = mul_chk(A.den, Bl.den);
    if (index > 0 && den != 1) throw std::invalid_argument("hacs_jl::product: index only for integral lattices");
    return hnf(gens, den, index);
}

Lat MaxOrder::conj(const Lat& L) const {
    std::vector<Vec4> gens;
    for (const auto& r : L.h) gens.push_back(conj(r));
    return hnf(gens, L.den, L.den == 1 ? L.index() : 0);
}

Lat MaxOrder::right_order(const Lat& L) const {
    Lat R;
    for (int t = 0; t < 4; ++t) {
        i128 n = nrd(L.h[t]);  // b_t = h_t/den; b_t^{-1} L = conj(h_t) h_s / nrd(h_t)
        Vec4 c = conj(L.h[t]);
        std::vector<Vec4> gens;
        for (int s = 0; s < 4; ++s) gens.push_back(mul(c, L.h[s]));
        Lat X = hnf(gens, n);
        R = t ? intersect(R, X) : X;
    }
    return R;
}

Lat MaxOrder::left_order(const Lat& L) const {
    Lat R;
    for (int t = 0; t < 4; ++t) {
        i128 n = nrd(L.h[t]);
        Vec4 c = conj(L.h[t]);
        std::vector<Vec4> gens;
        for (int s = 0; s < 4; ++s) gens.push_back(mul(L.h[s], c));
        Lat X = hnf(gens, n);
        R = t ? intersect(R, X) : X;
    }
    return R;
}

i128 MaxOrder::lattice_disc(const Lat& L) const {
    i128 g[4][4];
    Gram4 G = G_;
    for (int s = 0; s < 4; ++s)
        for (int t = 0; t < 4; ++t) {
            i128 v = 0;
            for (int i = 0; i < 4; ++i)
                for (int j = 0; j < 4; ++j)
                    v = add_chk(v, mul_chk(L.h[s][i], mul_chk(G.g[i][j], L.h[t][j])));
            g[s][t] = v;
        }
    i128 d = det4(g);
    if (L.den != 1) {
        i128 d8 = 1;
        for (int k = 0; k < 8; ++k) d8 = mul_chk(d8, L.den);
        d = exact_div(d, d8);
    }
    return d < 0 ? -d : d;
}

Lat MaxOrder::eichler_order(i64 M) const {
    if (D() % M == 0 || !is_prime(M)) throw std::invalid_argument("hacs_jl::eichler_order: M prime, M not dividing D");
    // first alpha in O (coordinates in [0,M)^4, lexicographic) with nrd(alpha) = 0 mod M, alpha not in M O
    for (i64 m = 1; m < M * M * M * M; ++m) {
        Vec4 a{{m % M, (m / M) % M, (m / M / M) % M, (m / M / M / M) % M}};
        if (mod128(nrd(a), M)) continue;
        std::vector<Vec4> gens;
        Lat O = unit();
        for (int s = 0; s < 4; ++s) gens.push_back(mul(O.h[s], a));
        for (int s = 0; s < 4; ++s) {
            Vec4 e{{0, 0, 0, 0}};
            e[s] = M;
            gens.push_back(e);
        }
        Lat J = hnf(gens, 1, (i128)M * M);
        return intersect(O, right_order(J));
    }
    throw std::runtime_error("hacs_jl::eichler_order: no zero divisor found");
}

