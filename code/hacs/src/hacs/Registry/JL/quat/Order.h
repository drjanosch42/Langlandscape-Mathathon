// hacs_jl quaternion core (WP HJ-1): a maximal order O of B_D = (a, b)_Q and lattice arithmetic in O-coordinates.
//
// Construction (documented change of basis w.r.t. quat.py). quat.py takes PARI's alginit basis, which we do not
// reproduce. Here O is obtained from Z<1, i, j, k> (reduced discriminant 4ab) by p-saturation: for each prime p with
// p^2 | disc / D^2 we search x in (1/p) O \ O with integral trd and nrd such that the ring generated by O and x is an
// order (closure under products, all trd(x conj y), nrd(x) integral), and replace O by it, until disc(O) = D^2
// (det of the trd Gram matrix; equivalently the reduced discriminant is D, so O is maximal). The basis of O is the
// canonical lower-triangular HNF of O in the standard basis 1, i, j, k, so e_0 = 1. All class-set invariants (h, the
// |Gamma_x| multiset, Brandt matrices up to class permutation, mass) are basis-independent; the self-test compares
// those, plus disc = D^2 and (a, b), with code/results/s01.
//
// Elements of O are integer coordinate vectors w.r.t. e_0..e_3 (Vec4); lattices are Lat in the same coordinates.
#pragma once

#include "Lattice.h"

namespace hacs_jl {

class MaxOrder {
public:
    explicit MaxOrder(i64 D);
    MaxOrder(i64 D, i64 a, i64 b);

    const QuatAlgebra& algebra() const { return B_; }
    i64 D() const { return B_.D(); }
    // basis e_t = E[t] / den in the standard basis 1, i, j, k
    const std::array<Vec4, 4>& std_basis() const { return E_; }
    i128 std_den() const { return den_; }

    Vec4 mul(const Vec4& x, const Vec4& y) const;   // product in O-coordinates
    Vec4 conj(const Vec4& x) const;
    i128 trd(const Vec4& x) const;
    i128 nrd(const Vec4& x) const;                  // exact (always an integer on O)
    const Gram4& gram() const { return G_; }        // G[s][t] = trd(e_s conj e_t); x^T G x = 2 nrd(x)
    const Embedding& embedding() const { return emb_; }
    i128 disc() const;                              // |det G| (= D^2)
    const i64 (&mult_table() const)[4][4][4] { return C_; }  // e_s e_t = sum_u C[s][t][u] e_u

    QElt to_std(const Vec4& x, i128 den = 1) const;

    // ---- lattices in O-coordinates
    Lat unit() const;                                                     // O
    // L1 * L2 (rational lattices allowed). index > 0: index of the numerator lattice, known a priori (fast path).
    Lat product(const Lat& A, const Lat& Bl, i128 index = 0) const;
    Lat conj(const Lat& L) const;
    Lat right_order(const Lat& L) const;   // {x : L x subset L}, generic (colon via intersections)
    Lat left_order(const Lat& L) const;    // {x : x L subset L}
    i128 lattice_disc(const Lat& L) const; // |det of the trd Gram| of a den=1 lattice
    // Eichler order O cap O_r(J), J the first M-neighbour (M prime, M not dividing D) of O, as in brandt.py
    Lat eichler_order(i64 M) const;

private:
    void build();
    QuatAlgebra B_;
    std::array<Vec4, 4> E_{};
    i128 den_ = 1;
    i64 C_[4][4][4];
    i128 tr_[4];
    Gram4 G_;
    Embedding emb_;
};

}  // namespace hacs_jl
