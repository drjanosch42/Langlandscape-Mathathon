// ===========================================================================
// Langlandscape JL extension (not upstream HACS; code/hacs/CHANGES.md, WP HJ-6-min, plan/hacs/HACS-JL-PLAN.md Sec. 3.2
// `Lattice2HeckeZ`).  Reads a weight-2 Brandt lattice record (`langlandscape_brandt/v1`, its `free_block_z` record, HJ-B0 spec
// plan/hacs/freeblockz-export-format.md) into an integral_descent::modexport::FreeBlockZ plus its operator list, and runs on it
//   (a) the shipped HACS reads  heckez::local::LatticeFromFreeZ -> ReadLocal  (EXW entry point), and
//   (b) Lane B's own reads with HACS primitives (Charpoly / DivideByRoot / SmithValuations / AlgebraClosure over Z/ell^K).
// Every value is *computed (HACS ReadLocal on a JL lattice)*; no record word of [C] is claimed for a JL lattice (contract-first rule):
// HACS's own status words are passed through a sanitiser (JlWord) before they are printed.
//
// Column convention (binding, HJ-B0 Sec. 2): T_p b_j = sum_i F_ij b_i, b_j = 1_{c_j}; F = B_p of brandt.py, NO transpose; row sums p+1.
// ===========================================================================

#include <cstdint>
#include <string>
#include <vector>

#include "../../Integral/Descent/DescentModuleExportZ.h"
#include "../../Integral/HeckeZLocal.h"

namespace hacs_jl {

// One weight-2 Brandt lattice (the fields of the free_block_z record Lane B uses; unknown fields are ignored on read).
struct BrandtRecord {
    std::string where;                    // the file (or "inline:<name>")
    std::string writer;                   // data.writer (logged, never branched on)
    std::string status;                   // "ok" | "rank0" | "no_integral_basis"
    uint32_t D = 0, M = 1, k = 2, n = 0, N = 0;
    uint32_t r = 0;                       // rank L = h
    std::vector<uint32_t> ops;            // ascending
    std::vector<std::vector<nf::BigInt>> F;   // per op, r x r row-major (flat)
    std::vector<std::string> F_fnv_json;  // per op, as written ("" when absent)
    std::vector<uint64_t> F_fnv;          // per op, recomputed here (MatrixFnv)
    uint32_t fnv_mismatch = 0;            // ops whose written F_fnv differs from the recomputed one
    std::vector<std::string> proof;
    std::string basis_rule, convention;
    std::vector<uint64_t> gammas;         // |Gamma_c| incl. +-1 (optional)
    int64_t d_algebra = -1;               // -1: absent
    int64_t e_eis = -1;                   // -1: absent
    std::vector<std::string> notes;       // tolerant-reader notes (aliases used, defaults filled)
};

// Parse one JSON text; false + *err on failure (schema mismatch, missing required field, malformed F).
bool ParseBrandtRecord(const std::string& text, const std::string& where, BrandtRecord* out, std::string* err);
// Files to read from a path: a *.json file, an index.json (the files it names, else its directory), or a directory (its index.json
// if present, else every *.json except index.json), sorted by (D, name).
std::vector<std::string> BrandtInputFiles(const std::string& path, std::string* err);

// The FreeBlockZ of the record (F, F_fnv, proof, basis_rule; the other members at the HJ-B0 Sec. 3 defaults).
integral_descent::modexport::FreeBlockZ ToFreeBlockZ(const BrandtRecord& R);
// The same block on L (+) L (block diagonal, rank 2r): see JlRead::readlocal_LL.
integral_descent::modexport::FreeBlockZ DoubledFreeBlockZ(const BrandtRecord& R);

// The ell-adic valuation of num((N-1)/12) (the Mazur prediction at prime level N, M = 1); 0 otherwise.
uint32_t MazurValuation(uint32_t N, uint64_t ell);
uint64_t MazurNumber(uint32_t N);   // num((N-1)/12)

struct OwnRead {                      // Lane B's own reads on L / ell^K (undoubled)
    std::string status;               // "ok" | "open(precision)" | "inconsistent" | "not_exact"
    int32_t v_cong = -1;              // v_ell of L / (L_eis (+) L_cusp) (all ops agreeing), -1 unread
    std::string per_op;               // "p:v=..:a=..:eta=..|..."
    int32_t v_gP_local = -1;          // min_p v_ell c_p(lambda_p)
    uint32_t T_gens = 0;              // dim_F_ell of T/ell (the algebra generated by P mod ell^K, generators)
    uint32_t T_len = 0;               // log_ell |T (x) Z/ell^K|
    uint32_t A1_dim = 0;              // dim_F_ell of the F_ell-algebra generated by P mod ell
    int32_t v_mass = -1;              // v_ell of [phi(L) : phi(L_eis)] from gammas (exact, -1: no gammas)
};

struct JlRead {
    uint32_t D = 0, M = 1, k = 2, N = 0, h = 0;
    uint64_t ell = 0;
    uint32_t K = 0;
    std::vector<uint32_t> P;
    std::string t_ell;                // ReadPrimes word, or "omitted(not_in_record)"
    std::string lm_status;            // LatticeFromFreeZ status
    // ReadLocal on L itself (the HJ-B0 Sec. 5 call): (C3), (2.4), (2.5) are meaningful; its at-root read uses the monic square root
    // of chi/(x - lambda)^r (HACS's H^1 carries S_k twice), which does not exist on L, where S_k occurs once -> root "inconsistent".
    heckez::local::LocalRead plain;
    // ReadLocal on L (+) L with r_eis = 2 * e_eis: chi = (x - lambda)^2 c^2, so the at-root read runs with the annihilator c of the cusp
    // part of L; eta_{L+L} = eta_L (+) eta_L, v_eta = v_ell(congruence module of L).
    heckez::local::LocalRead LL;
    bool ran_plain = false, ran_LL = false;
    OwnRead own;
    double seconds = 0;
    std::string json() const;         // the @@JL_READ payload (schema jl_lattice_read/v1)
};

// Reads at (ell, K).  P = ops (p | N dropped).  ell | N: no read (lm_status "skipped(ell|N)").
JlRead RunJlRead(const BrandtRecord& R, uint64_t ell, uint32_t K, bool do_plain = true, bool do_LL = true);

// No word of HACS's [C] record vocabulary that claims a certificate is printed for a JL lattice: "certified" -> "met(hacs_word)".
std::string JlWord(const std::string& hacs_word);

}  // namespace hacs_jl

#endif
