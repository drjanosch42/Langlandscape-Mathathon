"""Congruence modules over Z from the EXACT integer Hecke matrices that HACS exports (descent(D,n,P).module_Z(), free block F of
T_p on L = H^1(Gamma_0(D); Sym^n Z^2)/tors, p in P, p not dividing D).  No HACS code is re-implemented: this script only does
lattice arithmetic on the exported matrices.

  T_P      := the Z-subalgebra of End_Z(L) generated by {F_p : p in P}   (a subring of the anemic Hecke algebra T^an)
  V_A      := Q-subspace of L(x)Q cut out by a set A of Hecke eigen-systems (A in {eis, old_cusp (= level-1 cusp forms), new})
  J_A      := Ann_{T_P}(V_A) = ker(T_P -> End(V_A))
  C(A, B)  := T_P / (J_A + J_B)      (the congruence module of the A- and B-parts of T_P; finite)
Since T_P is contained in T^an, C(A,B) computed for T_P is a MULTIPLE of the true congruence module of T^an (upper bound, prime by
prime); it equals it at every prime ell where T_P (x) Z_ell = T^an (x) Z_ell.
Old systems: Eisenstein a_p = 1 + p^(k-1); level-1 cusp forms (k <= 14 in the grid: only Delta, k = 12; tau(p) computed below by the
q-expansion of Delta and cross-checked against HACS's level-1 charpoly).
Usage: congruence_modules.py <datadir>   -> writes <datadir>/congruence_modules.json and prints a table."""
import json, os, sys
from math import gcd
from sympy import factorint, Matrix
from sympy.polys.matrices import DomainMatrix
from sympy.polys.domains import ZZ, QQ
from sympy.matrices.normalforms import smith_normal_form

DATA = sys.argv[1]

def tau_list(N):
    # Delta = q prod (1-q^m)^24, coefficients up to q^N (stdlib integers)
    c = [0] * (N + 1); c[0] = 1
    for m in range(1, N + 1):
        for _ in range(24):
            for i in range(N, m - 1, -1): c[i] -= c[i - m]
    return [0] + c[:N]   # tau(i) = coefficient of q^i
TAU = tau_list(40)
assert TAU[2] == -24 and TAU[3] == 252 and TAU[5] == 4830 and TAU[7] == -16744

def hnf_insert(basis, v):
    """basis: dict pivot -> row (integer lists), echelon by pivot index; insert v, return True if lattice grew."""
    v = list(v)
    while True:
        piv = next((i for i, x in enumerate(v) if x != 0), None)
        if piv is None: return False
        if piv not in basis:
            if v[piv] < 0: v = [-x for x in v]
            basis[piv] = v; return True
        b = basis[piv]
        # Euclid between b and v on column piv
        while v[piv] != 0:
            q = b[piv] // v[piv]
            b = [x - q * y for x, y in zip(b, v)]
            b, v = v, b
        if b[piv] < 0: b = [-x for x in b]
        basis[piv] = b
        # v now has 0 at piv; continue inserting v

def hnf_rows(rows, ncols):
    basis = {}
    for r in rows: hnf_insert(basis, r)
    return [basis[k] for k in sorted(basis)]

def int_kernel(cond_rows, s):
    """{c in Z^s : sum_i c_i cond_rows[i] = 0} via HNF of [cond | I]."""
    m = len(cond_rows[0]) if cond_rows else 0
    aug = [list(cond_rows[i]) + [1 if j == i else 0 for j in range(s)] for i in range(s)]
    H = hnf_rows(aug, m + s)
    return [r[m:] for r in H if all(x == 0 for x in r[:m])]

def matmul(A, B):
    n, k, m = len(A), len(B), len(B[0])
    Bt = list(zip(*B))
    return [[sum(a * b for a, b in zip(A[i], Bt[j])) for j in range(m)] for i in range(n)]

def flat(M): return [x for r in M for x in r]
def unflat(v, r): return [v[i * r:(i + 1) * r] for i in range(r)]

def algebra_basis(gens, r):
    I = [[1 if i == j else 0 for j in range(r)] for i in range(r)]
    basis = {}; hnf_insert(basis, flat(I))
    changed = True
    while changed:
        changed = False
        cur = [basis[k] for k in sorted(basis)]
        for b in cur:
            B = unflat(b, r)
            for g in gens:
                if hnf_insert(basis, flat(matmul(B, g))): changed = True
    return [unflat(basis[k], r) for k in sorted(basis)]

def poly_at(coeffs_high_to_low, M, r):
    R = [[0] * r for _ in range(r)]
    for c in coeffs_high_to_low:
        R = matmul(R, M)
        for i in range(r): R[i][i] += c
    return R

def nullspace_Q(rows, r):
    if not rows: return [[1 if i == j else 0 for j in range(r)] for i in range(r)]
    D = DomainMatrix([[QQ(x) for x in row] for row in rows], (len(rows), r), QQ)
    N = D.nullspace().to_Matrix()   # rows = basis vectors of the right kernel
    out = []
    for i in range(N.rows):
        v = [N[i, j] for j in range(r)]
        den = 1
        for x in v: den = den * x.q // gcd(den, x.q)
        out.append([int(x * den) for x in v])
    return out

def smith(rows, s):
    if not rows: return ["0"] * s
    M = Matrix(rows)
    S = smith_normal_form(M, domain=ZZ)
    d = [abs(int(S[i, i])) for i in range(min(S.rows, S.cols))]
    d += [0] * (s - len(d))
    return [x for x in d if x != 1]

def run_cell(D, n):
    d = json.load(open(os.path.join(DATA, f"cell_D{D}_n{n}.json")))
    k = n + 2
    Fs = {int(p): [[int(x) for x in row] for row in F] for p, F, _ in d["F"]}
    fact = {x["p"]: x for x in d["FACT"]}
    r = len(next(iter(Fs.values())))
    P = sorted(Fs)
    # old eigenvalues
    eis = {p: 1 + p ** (k - 1) for p in P}
    # level-1 cusp systems: from HACS's level-1 char_Z factors when cell_D1_n<n>.json (same P) is in DATA, else Delta (k = 12)
    f1 = os.path.join(DATA, f"cell_D1_n{n}.json")
    if os.path.exists(f1):
        d1 = json.load(open(f1)); assert d1["P"] == P
        oldf = {x["p"]: [[int(c) for c in fa["coefficients"]] for fa in x["factors"]
                         if [int(c) for c in fa["coefficients"]] != [1, -eis[x["p"]]]] for x in d1["FACT"]}
    else:
        oldf = {p: [[1, -TAU[p]]] for p in P} if k == 12 else {p: [] for p in P}
    oldc = oldf if any(oldf.values()) else None
    # Q-subspaces
    def ker_inter(polys, primes=None):   # polys: p -> list of high->low coefficient lists (product taken)
        rows = []
        for p in (primes or P):
            Mp = [[1 if i == j else 0 for j in range(r)] for i in range(r)]
            for c in polys[p]: Mp = matmul(Mp, poly_at(c, Fs[p], r))
            rows += Mp
        return nullspace_Q(rows, r)
    newpolys = {}
    for p in P:
        fl = []
        for f in fact[p]["factors"]:
            c = [int(x) for x in f["coefficients"]]
            if c == [1, -eis[p]] or (oldc and c in oldc[p]): continue
            fl.append(c)
        newpolys[p] = fl
    # one prime suffices when the three kernels have dimensions summing to rank L (then each is exactly the joint eigenspace,
    # the operators being semisimple over Q: reduced_Q = true in the HACS record); otherwise intersect over all of P
    for prim in [[p] for p in P] + [P]:
        V = {"eis": ker_inter({p: [[1, -eis[p]]] for p in P}, prim),
             "new": ker_inter(newpolys, prim) if any(newpolys.values()) else []}
        V["old_cusp"] = ker_inter(oldc, prim) if oldc else []
        if sum(len(v) for v in V.values()) == r: break
    subspace_primes = prim
    dims = {a: len(v) for a, v in V.items()}
    assert sum(dims.values()) == r, (D, n, dims, r)
    V["old"] = V["eis"] + V["old_cusp"]
    V["cusp"] = V["old_cusp"] + V["new"]
    # T_P as a lattice via a cyclic vector v (t -> t.v is injective for v with nonzero projection on every eigen-component,
    # checked below: rank(T_P v) must equal dim_Q T_P(x)Q, computed independently as the number of distinct joint systems).
    import random
    rnd = random.Random(20261113)
    v = [rnd.randint(-50, 50) for _ in range(r)]
    basis = {}; hnf_insert(basis, v)
    changed = True
    while changed:
        changed = False
        for b in [basis[q] for q in sorted(basis)]:
            for p in P:
                w = [sum(Fs[p][i][j] * b[j] for j in range(r)) for i in range(r)]
                if hnf_insert(basis, w): changed = True
    L = [basis[q] for q in sorted(basis)]
    s = len(L)
    # dim_Q of T(x)Q = number of distinct joint eigen-systems = 1 (Eisenstein, anemic) + [old cusp] + sum of degrees of new factors
    exp_s = (1 if dims["eis"] else 0) + (sum(len(c) - 1 for c in oldc[P[0]]) if (oldc and dims["old_cusp"]) else 0) + (len(newpolys[P[0]]) and sum(len(c) - 1 for c in newpolys[P[0]]))
    # complement subspaces: W_A = span of the other components; J_A = L cap W_A
    comps = ["eis", "old_cusp", "new"]
    groups = {"eis": ["eis"], "old_cusp": ["old_cusp"], "new": ["new"], "old": ["eis", "old_cusp"], "cusp": ["old_cusp", "new"]}
    def J(a):
        W = [x for c in comps if c not in groups[a] for x in V[c]]
        if not W: return []
        ann = nullspace_Q(W, r)              # functionals vanishing on W_A
        cond = [[sum(f[j] * l[j] for j in range(r)) for f in ann] for l in L]
        return int_kernel(cond, s)
    Js = {a: J(a) for a in groups}
    # coordinates of the lattice L relative to its own basis: J's are integer combinations of L's rows (Z^s)
    def C(a, b):
        if not any(V[c] for c in groups[a]) or not any(V[c] for c in groups[b]): return None
        return smith(Js[a] + Js[b], s)
    res = {"D": D, "n": n, "k": k, "P": P, "rank_L": r, "subspace_primes": subspace_primes, "dims": dims, "rank_T_P": s, "dim_TQ_expected": exp_s, "cyclic_vector_ok": s == exp_s,
           "C_old_new": C("old", "new"), "C_oldcusp_new": C("old_cusp", "new"), "C_eis_new": C("eis", "new"),
           "C_eis_cusp": C("eis", "cusp"), "C_eis_oldcusp": C("eis", "old_cusp")}
    for key in list(res):
        if key.startswith("C_") and res[key] is not None:
            tot = 1
            for x in res[key]: tot *= x
            res[key + "_order_factored"] = {str(q): e for q, e in factorint(tot).items()} if tot > 1 else {}
    return res

out = []
CELLS = [tuple(map(int, a.split(","))) for a in sys.argv[2:]] or [(D, n) for D in [3, 5, 7, 11, 13] for n in range(2, 13, 2)]
import time
for D, n in CELLS:
        t0 = time.time(); r = run_cell(D, n); r["seconds"] = round(time.time() - t0, 1); out.append(r)
        print(D, r["k"], "rank", r["rank_L"], r["dims"], "rkT", r["rank_T_P"], "| old/new", r["C_old_new"], r.get("C_old_new_order_factored"),
              "| oldcusp/new", r["C_oldcusp_new"], r.get("C_oldcusp_new_order_factored"), "| eis/cusp", r.get("C_eis_cusp_order_factored"), "| eis/new", r.get("C_eis_new_order_factored"), "| cyclic_ok", r["cyclic_vector_ok"], r["seconds"], "s", flush=True)
json.dump(out, open(os.path.join(DATA, "congruence_modules.json" if len(sys.argv) == 2 else "congruence_modules_partial.json"), "w"), indent=1)
