"""Build mathematics/submission/src/report.bib (BibTeX, for amsalpha) from the biblatex sources of mathematics/.

Sources: mathematics/references.bib, mathematics/bib/*.bib, mathematics/report/hypotheses.bib, plus the report's own
entries (src/report-own.bib, written by hand; it wins on duplicate keys). Conversions for classic BibTeX:
@software/@dataset -> @misc, date -> year, journaltitle -> journal; `note` fields of the literature entries are dropped
(they record local file paths and verification notes for the chapters, which the chapters print as \\lit pointers).
First occurrence of a key wins (own entries first).

Usage: python3 -I mathematics/submission/tools/build_bib.py
"""
import glob
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
MATH = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(MATH, "submission", "src", "report.bib")
OWN = os.path.join(MATH, "submission", "src", "report-own.bib")


def entries(text):
    """Yield (type, key, body) for each @type{key, ...} entry (brace-balanced)."""
    i = 0
    while True:
        m = re.compile(r"@(\w+)\s*\{\s*([^,\s]+)\s*,").search(text, i)
        if not m:
            return
        depth, j = 1, m.end()
        while depth and j < len(text):
            depth += {"{": 1, "}": -1}.get(text[j], 0)
            j += 1
        yield m.group(1).lower(), m.group(2), text[m.end():j - 1]
        i = j


def fields(body):
    """Split an entry body into (name, value) pairs, brace-balanced."""
    out, i = [], 0
    while True:
        m = re.compile(r"\s*(\w+)\s*=\s*").match(body, i)
        if not m:
            return out
        j = m.end()
        if j < len(body) and body[j] == "{":
            depth, k = 1, j + 1
            while depth and k < len(body):
                depth += {"{": 1, "}": -1}.get(body[k], 0)
                k += 1
            val = body[j:k]
        else:
            k = j
            while k < len(body) and body[k] not in ",\n":
                k += 1
            val = body[j:k].strip()
        out.append((m.group(1).lower(), val))
        i = k
        m2 = re.compile(r"\s*,?").match(body, i)
        i = m2.end()


def convert(typ, flds, own):
    typ = {"software": "misc", "dataset": "misc", "online": "misc", "report": "techreport"}.get(typ, typ)
    res = []
    names = {n for n, _ in flds}
    for n, v in flds:
        if n == "date" and "year" not in names:
            n, v = "year", "{" + re.sub(r"[{}]", "", v)[:4] + "}"
        if n == "journaltitle":
            n = "journal"
        if n == "note" and not own:
            continue
        if n in ("eprinttype",):
            continue
        res.append((n, v))
    return typ, res


def main():
    srcs = [OWN, os.path.join(MATH, "references.bib")] + sorted(glob.glob(os.path.join(MATH, "bib", "*.bib"))) + [
        os.path.join(MATH, "report", "hypotheses.bib")]
    seen, chunks = set(), []
    for path in srcs:
        own = path == OWN
        with open(path, encoding="utf-8") as fh:
            text = "\n".join(l for l in fh.read().splitlines() if not l.lstrip().startswith("%"))
        for typ, key, body in entries(text):
            if key in seen:
                continue
            seen.add(key)
            typ, flds = convert(typ, fields(body), own)
            lines = ",\n".join(f"  {n} = {v}" for n, v in flds)
            chunks.append(f"@{typ}{{{key},\n{lines}\n}}\n")
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("% SPDX-License-Identifier: CC-BY-4.0\n"
                 "% Copyright (C) 2026 Fabian Januszewski, Abhijit (the Langlandscape team)\n"
                 "% GENERATED by mathematics/submission/tools/build_bib.py -- do not edit; edit src/report-own.bib.\n\n")
        fh.write("\n".join(chunks))
    print(f"{len(chunks)} entries -> {OUT}")


if __name__ == "__main__":
    main()
