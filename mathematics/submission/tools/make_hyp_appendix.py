"""Make the text of Appendix A of the submission report from the hypotheses report.

Reads mathematics/report/hypotheses.tex (the body of standalone-hypotheses.tex), inlines its two TikZ figures
(report/figures/hyp-*.tex) and its generated table rows (report/generated/hyp-table.tex, used via \\hyptablerows),
demotes the sectioning by one level (it becomes the subsections of one appendix section), strips comment lines and
writes mathematics/submission/src/appendix-hyp-body.tex. The text itself is not changed, except for the
anonymising replacements in ANON (machine names and one attribution).
The macros it needs are in src/hyp-macros.tex (a tcolorbox-free copy of report/hyp-preamble.tex).

Usage: python3 -I mathematics/submission/tools/make_hyp_appendix.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
MATH = os.path.abspath(os.path.join(HERE, "..", ".."))
REP = os.path.join(MATH, "report")
OUT = os.path.join(MATH, "submission", "src", "appendix-hyp-body.tex")


ANON = [("TITAN ", "build machine A "), ("CONCEPTD ", "build machine B "),
        ("TITAN round", "build-machine round"),
        ("\\lname{lean/Langlandscape/.titan/out/axcount.txt}", "the gate's axiom-count file"),
        ("\\lname{origin/conceptd/s04-int15-1}", "the second build machine's result branch for that gate"),
        ("\\lname{origin/titan/s04-gate1-1}", "the build machine's result branch for that gate"), ("FD1 decided, Fabian, 2026-11-15", "FD1 decided, team decision, 2026-11-15")]


def strip_comments(text):
    out = []
    for line in text.splitlines():
        if line.lstrip().startswith("%"):
            continue
        out.append(line)
    return "\n".join(out)


def read(rel):
    with open(os.path.join(MATH, rel), encoding="utf-8") as fh:
        return strip_comments(fh.read())


def main():
    body = read("report/hypotheses.tex")
    for fig in ("hyp-deps", "hyp-timeline"):
        body = body.replace("\\input{report/figures/%s}" % fig, read("report/figures/%s.tex" % fig).strip())
    body = body.replace("\\hyptablerows", read("report/generated/hyp-table.tex").strip())
    body = re.sub(r"\\subsection(\*?)\{", r"\\subsubsection\1{", body)
    body = re.sub(r"\\section(\*?)\{", r"\\subsection\1{", body)
    body = body.replace("\\begin{figure}[!p]", "\\begin{figure}[htbp]").replace("\\begin{figure}[!tbp]",
                                                                                 "\\begin{figure}[htbp]")
    # Anonymity of the report body (only the title block names persons, machines and the repository): the machine
    # names become neutral words, the one decision attribution becomes "team decision".
    for old, new in ANON:
        body = body.replace(old, new)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("% SPDX-License-Identifier: CC-BY-4.0\n"
                 "% Copyright (C) 2026 Fabian Januszewski, Abhijit (the Langlandscape team)\n"
                 "% GENERATED by mathematics/submission/tools/make_hyp_appendix.py from mathematics/report/hypotheses.tex\n"
                 "% (figures and table rows inlined, sectioning demoted by one level) -- do not edit by hand.\n\n")
        fh.write(body.strip() + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
