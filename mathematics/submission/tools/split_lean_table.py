"""Split generated/lean-table.tex (Tables L1, L2, L3) into src/lean-table-L12.tex (Section 8) and src/lean-table-L3.tex
(Appendix B) at the heading of Table L3. The text is not changed. Re-run after tools/lean_table.py.

Usage: python3 -I mathematics/submission/tools/split_lean_table.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SUB = os.path.abspath(os.path.join(HERE, ".."))
MARK = "\\subsection*{Table L3"
HEAD = ("% SPDX-License-Identifier: CC-BY-4.0\n% Copyright (C) 2026 the Langlandscape team\n"
        "% GENERATED by tools/split_lean_table.py from generated/lean-table.tex (%s) -- do not edit by hand.\n\n")


def main():
    with open(os.path.join(SUB, "generated", "lean-table.tex"), encoding="utf-8") as fh:
        text = fh.read()
    i = text.index(MARK)
    body12 = "\n".join(l for l in text[:i].splitlines() if not l.lstrip().startswith("%"))
    for name, part, what in (("lean-table-L12.tex", body12, "Tables L1, L2"), ("lean-table-L3.tex", text[i:], "Table L3")):
        with open(os.path.join(SUB, "src", name), "w", encoding="utf-8") as fh:
            fh.write(HEAD.replace("(%s)", "(" + what + ")") + part.strip() + "\n")
    print("split at offset", i)


if __name__ == "__main__":
    main()
